import statistics as st
def q(d):
    d=sorted(d); n=len(d)
    if n%2: lo=d[:n//2]; hi=d[n//2+1:]
    else: lo=d[:n//2]; hi=d[n//2:]
    return st.median(lo), st.median(d), st.median(hi)
def hist(d,start,w,k):
    c=[sum(1 for x in d if start+i*w<=x<start+(i+1)*w) for i in range(k)]; return c
