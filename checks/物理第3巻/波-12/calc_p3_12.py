def rainbow(n):
    best=None
    for i in range(1,90000):
        th=rad(i/1000); r=asin(sin(th)/n); D=pi+2*th-4*r
        if best is None or D<best[0]: best=(D,i/1000,deg(r))
    return 180-deg(best[0]), best[1], best[2]
