def rainbow2(n):
    best=None
    for i in range(1,90000):
        th=rad(i/1000); r=asin(sin(th)/n); D=2*pi+2*th-6*r
        if best is None or D<best[0]: best=(D,i/1000)
    return deg(best[0])-180
