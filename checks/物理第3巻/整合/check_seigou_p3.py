# 物理第3巻 整合の組：数を変えた所の検算（python3 checks/物理第3巻/整合/check_seigou_p3.py）
import math

print('== 波-4 じぶんでとこう（熱-12 のカップ：C=840 J/K、R=3.61 K/W。熱-12 ③の表の値にそろえた）')
C, R = 840, 3.61
P = 30 / R
tau = C * R
print(f'保つ力 30/R = {P:.2f} W  → 約8.3 W')
print(f'時定数 RC = {tau:.0f} s = {tau/60:.1f} 分 → 約3030 s、約51分')
th = 20 + 30 * (1 - math.exp(-50 * 60 / tau))
print(f'50分後 = {th:.1f} ℃ → 約39 ℃')

print('== 波-5 水の音の速さ（K=2.2 GPa、ρ=998 kg/m^3。波-9 ④・巻末の 20 ℃の水 1482 m/s にそろえて 1480）')
c = math.sqrt(2.2e9 / 998)
print(f'sqrt(K/ρ) = {c:.1f} m/s → 3けたで 1480 m/s')
print(f'例題2 (2) 1480/440 = {1480/440:.2f} m → 約3.4 m、空気との比 1480/343 = {1480/343:.2f} → 約4.3倍')
print(f'章末問題 1480/880 = {1480/880:.2f} m → 約1.7 m')

print('== 波-13 ⑧ 強制振動の振幅（波-2 ④の倍率の式で ζ=0 とおく）')
# |X|/(F0/k) = 1/|1-(w/wn)^2|  →  X = F0/(m (wn^2 - w^2))
m, wn, w, F0 = 1.0, 3.0, 1.0, 2.0
k = m * wn**2
X1 = (F0 / k) / abs(1 - (w / wn)**2)
X2 = F0 / (m * (wn**2 - w**2))
print(f'倍率の式 {X1:.6f} と F0/(m(ωn²−ω²)) {X2:.6f} は同じ')
