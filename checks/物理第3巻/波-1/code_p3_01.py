# 波-1 ⑪ の囲みのプログラム（本文と同じもの）。出力を本文の実行結果に写す。
k, m = 200, 0.5           # ばね定数、質量
dt = 0.005                # Δt（秒）。1周期は約0.314秒
x1, v1 = 0.1, 0.0         # オイラー法
x2, v2 = 0.1, 0.0         # 速度を先に進めるオイラー法
for step in range(1, 316):         # 315歩＝約5周期
    a1 = -k / m * x1
    x1, v1 = x1 + v1 * dt, v1 + a1 * dt     # 今の速さで位置、今の加速度で速度
    a2 = -k / m * x2
    v2 = v2 + a2 * dt                       # 速度を先に新しくし
    x2 = x2 + v2 * dt                       # 新しい速度で位置を進める
    if step % 63 == 0:                      # 約1周期ごとに表示
        E1 = 0.5 * m * v1**2 + 0.5 * k * x1**2
        E2 = 0.5 * m * v2**2 + 0.5 * k * x2**2
        print(round(step * dt, 3), round(E1, 3), round(E2, 3))
