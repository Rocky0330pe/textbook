#!/usr/bin/env python3
"""波-9 音の大きさをはかる：音速・デシベル・騒音 の数値の検算（組 波W5）。
python3 checks/物理第3巻/波-9/calc_p3_09.py
"""
import math

pi = math.pi
log10 = math.log10


def p(label, *vals):
    print(label, ':', ', '.join(f'{v:.6g}' for v in vals))


gam, Rs = 1.4, 287.0          # 熱-3 の空気の値
T0 = 273.15


def c_air(theta):
    return math.sqrt(gam * Rs * (T0 + theta))


rho_air = 101325 / (Rs * (T0 + 20))
Za = rho_air * c_air(20)
p('空気 20℃ の密度・音速・ρc', rho_air, c_air(20), Za)
p('ヘリウム（熱-4 の jibun）', math.sqrt(5 / 3 * 2077 * 293.15))
p('ニュートン 20℃', math.sqrt(Rs * 293.15))

print('== ① 音圧と空気の動き')
u1 = 1 / Za
p('1 Pa（実効値）の空気の速さ mm/s', u1 * 1e3)
p('1 kHz でのずれ（実効値）μm', u1 / (2 * pi * 1000) * 1e6)
u0 = 20e-6 / Za
p('20 μPa の速さ m/s・1 kHz でのずれ nm', u0, u0 / (2 * pi * 1000) * 1e9)
p('大気圧に対する 1 Pa の割合', 1 / 101325)
p('スピーカー 例題: 94 dB・100 Hz のずれ（振幅）mm', math.sqrt(2) * u1 / (2 * pi * 100) * 1e3)

print('== ② 雷・光')
p('雷 3 s・340 m/s → km', 340 * 3 / 1000)
p('光が 1 km 進む時間 μs', 1000 / 3e8 * 1e6)
p('雷 5 s', 340 * 5 / 1000)
p('こだま 50 m・0.29 s → m/s', 2 * 50 / 0.29)
p('こだま jibun 85 m・0.50 s', 2 * 85 / 0.50)
p('花火 2.5 s → km (340)', 340 * 2.5 / 1000)

print('== ③④ 波動方程式・液体・固体')
Kw, rw = 2.2e9, 998.0
p('水 √(K/ρ)', math.sqrt(Kw / rw))
Es, rs, nu = 205e9, 7850.0, 0.3
Ks = Es / (3 * (1 - 2 * nu))
Gs = Es / (2 * (1 + nu))
p('鋼 K, G (GPa)', Ks / 1e9, Gs / 1e9)
p('鋼 棒 √(E/ρ)', math.sqrt(Es / rs))
p('鋼 広い固体の縦波 √((K+4G/3)/ρ)', math.sqrt((Ks + 4 * Gs / 3) / rs))
p('鋼 横波 √(G/ρ) (G=79)', math.sqrt(Gs / rs), math.sqrt(79e9 / rs))
p('空気の K_s=γp, √(K_s/ρ)', gam * 101325, math.sqrt(gam * 101325 / rho_air))
p('レール 1 km：鋼の棒・空気 s', 1000 / math.sqrt(Es / rs), 1000 / 343)
p('レール jibun 500 m: 鋼・空気・差', 500 / 5100, 500 / 343, 500 / 343 - 500 / 5100)
p('水中 1 km の時間 s', 1000 / 1480)
p('水の K を 2倍にすると速さ', math.sqrt(2))
p('水 jibun 海水 K=2.34GPa ρ=1025', math.sqrt(2.34e9 / 1025))
p('空気 vs 水 ρc', Za, 1480 * 998)

print('== ⑤ 温度')
c0 = c_air(0)
p('0℃ の音速, 1次近似の傾き', c0, c0 / (2 * T0))
for th in (-40, -20, 0, 15, 20, 30, 40):
    p(f'{th}℃: 式・331.5+0.6θ・331.3+0.606θ', c_air(th), 331.5 + 0.6 * th, c0 + c0 / (2 * T0) * th)
p('分子の平均の速さとの比（熱-14 の 471 m/s）', 343 / 471)
p('30℃ の雷 3 s', c_air(30) * 3)
p('jibun -10℃ 331.5+0.6θ, 式', 331.5 - 6, c_air(-10))

print('== ⑥ dB')
p('1 Pa → dB', 20 * log10(1 / 20e-6))
p('20 μPa の強さ W/m² (=p²/ρc)', (20e-6) ** 2 / Za)
p('1 Pa の強さ W/m²', 1 / Za)
p('L_I と L_p の差 dB', 10 * log10(1 / Za / 1e-12) - 20 * log10(1 / 20e-6))
p('60 vs 30 dB：音圧比・強さ比', 10 ** (30 / 20), 10 ** 3)
p('jibun 90 vs 40: 音圧比・強さ比', 10 ** (50 / 20), 1e5)
p('音圧 2 倍 → dB', 20 * log10(2))
p('0.02 Pa の dB', 20 * log10(0.02 / 20e-6))
p('jibun 0.2 Pa → dB, 100 dB → Pa', 20 * log10(0.2 / 20e-6), 20e-6 * 10 ** (100 / 20))
p('痛い 20 Pa の dB', 20 * log10(20 / 20e-6))

print('== ⑦ 合成と距離')
def dbsum(*L):
    return 10 * log10(sum(10 ** (x / 10) for x in L))
p('80+80, 80+70', dbsum(80, 80), dbsum(80, 70))
p('jibun 70+70+70, 90+80', dbsum(70, 70, 70), dbsum(90, 80))
p('背景 差し引き 85 合計 82 背景 → 機械', 10 * log10(10 ** 8.5 - 10 ** 8.2))
p('10 log(4π)', 10 * log10(4 * pi))
p('L_W=100 dB, 10 m 自由空間', 100 - 20 * log10(10) - 11)
p('L_W=100 dB, 10 m 半自由空間(地面)', 100 - 20 * log10(10) - 8)
p('jibun L_W 95 dB 20 m (自由)', 95 - 20 * log10(20) - 11)
p('点音源 距離 2 倍 dB, 線音源 2 倍', -20 * log10(2), -10 * log10(2))
p('点 10 m で 70 → 40 m', 70 - 20 * log10(4))
p('線 10 m で 70 → 40 m', 70 - 10 * log10(4))
p('jibun 点 5 m 80 dB → 何 m で 60', 5 * 10 ** (20 / 20))
p('jibun 線 20 m で 75 → 80 m', 75 - 10 * log10(4))
for n in range(1, 11):
    pass
p('同じ音 n 台: 2,3,4,10', *[10 * log10(n) for n in (2, 3, 4, 10)])
p('差が 0,3,6,10 dB の足し算の増え分', *[10 * log10(1 + 10 ** (-d / 10)) for d in (0, 3, 6, 10)])

print('== ⑧ A 特性')
def Aw(f):
    f2 = f * f
    ra = (12194 ** 2 * f2 ** 2) / ((f2 + 20.6 ** 2) * math.sqrt((f2 + 107.7 ** 2) * (f2 + 737.9 ** 2)) * (f2 + 12194 ** 2))
    return 20 * log10(ra) + 2.00
for f in (31.5, 63, 100, 125, 250, 500, 1000, 2000, 4000, 8000, 16000):
    p(f'A({f})', Aw(f))
p('例題: 100 Hz 80 dB と 1 kHz 80 dB と 4 kHz 80 dB → dB(A)', 80 + Aw(100), 80 + Aw(1000), 80 + Aw(4000))
p('jibun 63 Hz 90 dB と 1k 70 dB の合計 dB と dB(A)', dbsum(90, 70), dbsum(90 + Aw(63), 70 + Aw(1000)))

print('== ⑨ 質量則')
def TL0(m, f):
    return 10 * log10(1 + (pi * f * m / Za) ** 2)
p('ガラス 5 mm 12.5 kg/m², 500 Hz：厳密・20log', TL0(12.5, 500), 20 * log10(pi * 500 * 12.5 / Za))
p('同 1000 Hz, 250 Hz', TL0(12.5, 1000), TL0(12.5, 250))
p('ガラス 10 mm 25 kg/m² 500 Hz', TL0(25, 500))
p('石こうボード 12.5 mm ρ≈ 640? 8 kg/m² 500 Hz', TL0(8, 500))
p('コンクリート 150 mm 2300 → 345 kg/m², 500 Hz', TL0(345, 500))
p('20log(π/ρc)', 20 * log10(pi / Za))
p('jibun 鉄板 1 mm 7.85 kg/m² 1000 Hz', TL0(7.85, 1000))
p('jibun コンクリート 120mm 276 kg/m² 125 Hz', TL0(0.12 * 2300, 125))
p('透過した音の割合 10^(-TL/10) 33.5', 10 ** (-TL0(12.5, 500) / 10))
p('外 75 dB の道路, ガラス 34 dB → 部屋', 75 - 33.5)

print('== ⑩ 残響')
p('定数 24 ln10 / c', 24 * math.log(10) / c_air(20))
V = 7 * 9 * 3
S = 2 * 7 * 9 + 2 * (7 + 9) * 3
p('教室 V, S', V, S)
p('残響 0.161 V/A：A=30', 0.161 * V / 30)
p('平均の吸音率 30/S', 30 / S)
p('jibun A=60', 0.161 * V / 60)
p('天井 63 m² を α 0.02→0.70 にしたとき A', 30 + 63 * (0.70 - 0.02), 0.161 * V / (30 + 63 * 0.68))
# ホール
Vh = 20000
p('ホール 20000 m³ で t=2.0 s の A', 0.161 * Vh / 2.0)
p('残響 60 dB の減り：1 s に何 dB（t=1.0）', 60 / 1.0)
p('平均自由行程 4V/S, 1 回あたりの時間', 4 * V / S, 4 * V / S / 343)
# 減り方の曲線
for t in (0, 0.25, 0.5, 0.75, 1.0):
    p(f't={t} s のレベル（t_R=1.0 s）', -60 * t / 1.0)

print('== 波長')
p('20 Hz・1 kHz・20 kHz の波長 m', 343 / 20, 343 / 1000, 343 / 20000)
p('jibun 水中 20 Hz-20 kHz', 1480 / 20, 1480 / 20000)
