print('== 力-14 図7 ムーディ線図：なめらかな管の線を Re=10^8 まで（コールブルックの式、ε=0）')
def lam_smooth(Re):
    l = 0.02
    for _ in range(200):
        l = (1 / (-2 * math.log10(2.51 / (Re * math.sqrt(l))))) ** 2
    return l
for x in (7.0, 7.2, 7.4, 7.6, 7.8, 8.0):
    l = lam_smooth(10 ** x)
    print('log10 Re=%.1f  λ=%.5f  log10 λ=%.4f' % (x, l, math.log10(l)))
print('目もり 0.005 → log10=%.3f' % math.log10(0.005))

