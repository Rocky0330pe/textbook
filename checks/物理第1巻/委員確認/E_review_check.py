print('== 力-14 ⑧ もっと知りたい（足した）：マレーの法則')
# 費用 C(R)=8μLQ^2/(πR^4)+bπR^2L を最小にする R で Q^2=bπ^2R^6/(16μ)
mu, Lg, b, Q = 3e-3, 1.0, 1000.0, 1e-6
f = lambda R: 8 * mu * Lg * Q ** 2 / (math.pi * R ** 4) + b * math.pi * R ** 2 * Lg
lo, hi = 1e-6, 1e-1
for _ in range(300):
    m1, m2 = lo + (hi - lo) / 3, hi - (hi - lo) / 3
    if f(m1) < f(m2): hi = m2
    else: lo = m1
Rbest = (lo + hi) / 2
print('数値で最小の R=%.5e、式 R=(16μQ^2/(bπ^2))^(1/6)=%.5e' % (Rbest, (16 * mu * Q ** 2 / (b * math.pi ** 2)) ** (1 / 6)))
