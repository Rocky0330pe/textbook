# チャレンジ11（差しかえ）：1辺2 mの正方形 A(0,0) ピン・B(2,0) ローラー・C(2,2)・D(0,2)、部材 AB BC CD DA AC、D に右向き 6 kN
P = {'A': (0, 0), 'B': (2, 0), 'C': (2, 2), 'D': (0, 2)}
Mb = ['AB', 'BC', 'CD', 'DA', 'AC']
R = [('A', 0), ('A', 1), ('B', 1)]
load = {'D': (6, 0)}
nd = list(P)
K = np.zeros((2 * len(nd), len(Mb) + len(R))); b = np.zeros(2 * len(nd))
for j, (i, k) in enumerate(Mb):
    e = np.subtract(P[k], P[i]); e = e / np.hypot(*e)
    K[2 * nd.index(i):2 * nd.index(i) + 2, j] += e
    K[2 * nd.index(k):2 * nd.index(k) + 2, j] -= e
for j, (i, d) in enumerate(R):
    K[2 * nd.index(i) + d, len(Mb) + j] = 1
for i, f in load.items():
    b[2 * nd.index(i):2 * nd.index(i) + 2] = -np.array(f)
chk('チャレンジ11(1) 未知数−式の数（0なら静定）', (len(Mb) + len(R)) - 2 * len(nd), 0, 0)
chk('チャレンジ11(1) 行列の行列式が0でない', int(abs(np.linalg.det(K)) > 1e-9), 1, 0)
x = dict(zip(Mb + ['RAx', 'RAy', 'RB'], np.linalg.solve(K, b)))
for s, want in [('AB', 0), ('BC', -6), ('CD', -6), ('DA', 0), ('AC', 6 * sqrt(2)),
                ('RAx', -6), ('RAy', -6), ('RB', 6)]:
    chk('チャレンジ11(2) ' + s + '（kN）', x[s], want, 1e-9)
chk('チャレンジ11(2) AC ≈ 8.5', 6 * sqrt(2), 8.49, 0.005)

