import math

ng = 0
def chk(name, got, want, tol=0.0):
    global ng
    ok = abs(got - want) <= tol
    if not ok:
        ng += 1
    print('%-4s %-58s 計算 %-12.6g 本文 %g' % ('OK' if ok else 'NG', name, got, want))

def trunc(x, nd=1):
    """安全の側（小さいほう）へ切り捨て（K-12）"""
    f = 10 ** nd
    return math.floor(x * f + 1e-9) / f

SY = 245.0
print('== K-12・R3-27：安全率を切り捨てる（力-9）')
# 例題5
seq5 = math.sqrt(80**2 - 80*(-20) + (-20)**2 + 3*30**2)
chk('例題5 ミーゼス応力', seq5, 105.4, 0.05)
chk('例題5 安全率（切り捨て）', trunc(SY/seq5), 2.3)
# じぶんでとこう5
seq = math.sqrt(50**2 - 50*10 + 10**2 + 3*15**2)
chk('じ5 ミーゼス応力', seq, 52.7, 0.05)
chk('じ5 安全率 4.65→4.6', trunc(SY/seq), 4.6)
# 例題6
chk('例題6（1）安全率 2.10→2.1', trunc(SY/116.6), 2.1)
chk('例題6（2）安全率 4.08→4.0', trunc(SY/60), 4.0)
# じぶんでとこう6
chk('じ6（1）安全率 2.45→2.4', trunc(SY/100), 2.4)
chk('じ6（2）安全率 2.72→2.7', trunc(SY/90), 2.7)
# 例題7
smis = math.sqrt(60**2 + 3*40**2); stre = math.sqrt(60**2 + 4*40**2)
chk('例題7 ミーゼス', smis, 91.7, 0.05)
chk('例題7 ミーゼスの安全率 2.67→2.6', trunc(SY/smis), 2.6)
chk('例題7 トレスカの安全率 2.45→2.4', trunc(SY/stre), 2.4)
# 章末問題7
m = math.sqrt(100**2 + 3*50**2); t = math.sqrt(100**2 + 4*50**2)
chk('章末7（1）ミーゼス', m, 132, 0.5)
chk('章末7（1）ミーゼスの安全率 1.85→1.8', trunc(SY/m), 1.8)
chk('章末7（1）トレスカの安全率 1.73→1.7', trunc(SY/t), 1.7)
chk('章末7（3）安全率 2.04→2.0', trunc(SY/120), 2.0)

print('== R3-11：モールの円の中心 c と半径 ρ（記号だけ変えた。数は同じ）')
c = (80 + (-20)) / 2; rho = math.hypot(50, 30)
chk('例題3 中心 c', c, 30)
chk('例題3 半径 ρ', rho, 58.3, 0.05)
chk('例題3 σ1 = c+ρ', c + rho, 88.3, 0.05)
chk('じ2 半径 ρ（τ=25 だけ）', math.hypot(0, 25), 25)

print('== R3-2：力-11 例題6 の回転数')
n = 3000 / 60
chk('n = 3000÷60（s^-1）', n, 50)
w = 2*math.pi*n; T = 100e3 / w
chk('ω', w, 314, 0.5)
chk('T', T, 318, 0.5)
chk('d（mm）', (16*T/(math.pi*50e6))**(1/3)*1000, 31.9, 0.05)

print('== K-6 で書きかえた式の形（数は同じ）')
# 力-8 じぶんでとこう4（2）
chk('力-8 じ4 σ = 205000×(15−30)÷50000', 205000*(15-30)/50000, -61.5, 0.01)
chk('力-8 じ12（1）', 2700*9.8*500**2/(2*69e9), 0.048, 0.0005)
chk('力-8 じ12（2）（m）', 270e6/(2700*9.8), 10204, 1)
chk('力-8 章末7 k（N/mm）', 205000*3.14/1000, 643.7, 0.05)
chk('力-8 章末9 伸び（m）', 7850*9.8*2000**2/(2*205e9), 0.751, 0.001)
# 力-9 G
chk('力-9 G 鋼 205÷(2×1.3)', 205/2.6, 78.8, 0.05)
chk('力-9 G アルミ 69÷(2×1.33)', 69/2.66, 25.9, 0.05)
chk('力-9 G 銅 117÷(2×1.34)', 117/2.68, 43.7, 0.05)
# 力-10
chk('力-10 両はし固定 δ の 1/5（384/(5·384/... )）', (1/384)/(5/384), 0.2, 1e-12)
