print('== 力-9 の不変量（もっと知りたい）')
sx, sy, tau = 80, -20, 30
s1, s2 = c + rho, c - rho
chk('σx+σy = σ1+σ2', s1 + s2, sx + sy, 1e-9)
chk('σxσy−τ² = σ1σ2', s1*s2, sx*sy - tau**2, 1e-9)
chk('σeq² = (σ1+σ2)² − 3σ1σ2', (s1+s2)**2 - 3*s1*s2, seq5**2, 1e-6)

print('NG の数:', ng)
