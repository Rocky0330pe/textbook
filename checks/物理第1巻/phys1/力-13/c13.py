# 力-13 流れを数える：例題・図・表の数値（組 P1-7）
from math import *
g=9.8; rw=1000.0; rair=1.2
def P(*a): print(*a)
A=lambda d: pi*d*d/4
P('--- 蛇口 Q=6 L/min d0=10 mm ---')
Q=6/1000/60; d0=0.010; v0=Q/A(d0)
P('Q',Q,'v0',v0)
for z in [0,0.05,0.10,0.15,0.20,0.30]:
    v=sqrt(v0**2+2*g*z); d=d0*sqrt(v0/v)
    P('z',z,'v',round(v,3),'d mm',round(d*1000,2))
P('--- 噴水 jibun: 上向き v0=5 m/s, d0=10 mm ---')
v0f=5.0; P('H', v0f**2/(2*g))
for z in [0,0.5,1.0]:
    v=sqrt(v0f**2-2*g*z); P('z',z,'v',v,'d mm',10*sqrt(v0f/v))
P('--- 例2 管 50→25 mm, 1 m/s ---')
P(1*(50/25)**2)
P('jibun 100→40 mm 1.5 m/s', 1.5*(100/40)**2)
P('--- 例3 給水管 20 mm, 20 L/min ---')
Q3=20/1000/60; P('v', Q3/A(0.020), 'Q', Q3)
P('jibun 13 mm 12 L/min', (12/1000/60)/A(0.013))
P('--- 質量流量 ---'); P('ex3 mdot', rw*Q3)
P('--- 例4 トリチェリ h=2 m ---')
v=sqrt(2*g*2); P('v',v,'穴 1 cm2 流量 L/s', v*1e-4*1000)
P('jibun h=5 m', sqrt(2*g*5), ' 0.8 m', sqrt(2*g*0.8))
P('--- 例5 タンクが空 ---')
At=1.0; a=1e-4; h0=2.0
t=At/a*sqrt(2*h0/g); P('t s',t,'min',t/60,'h',t/3600)
P('半分(1 m)まで', At/a*(sqrt(2*h0/g)-sqrt(2*1.0/g)))
P('Cd 0.6 なら', t/0.6/3600)
# Euler sim
dt=60.0; h=h0; tt=0; rows=[]
while h>0:
    rows.append((tt,h)); q=a*sqrt(2*g*h); h=h-q/At*dt; tt+=dt
P('Euler dt=60 空になる', tt, len(rows))
for (tt_,hh) in rows[::10]: P(' ',tt_, round(hh,3), 'exact', round((sqrt(h0)-a/At*sqrt(g/2)*tt_)**2 if sqrt(h0)-a/At*sqrt(g/2)*tt_>0 else 0,3))
P('jibun A=0.5 a=2 cm2 h=1.8', 0.5/2e-4*sqrt(2*1.8/g), '/60', 0.5/2e-4*sqrt(2*1.8/g)/60)
P('--- 例6 ベンチュリ 100→50 15 kPa ---')
A1=A(0.1); A2=A(0.05)
v2=sqrt(2*15e3/(rw*(1-(A2/A1)**2))); P('v2',v2,'Q',v2*A2,'L/s',v2*A2*1000, 'v1', v2*A2/A1)
P('jibun 80→40, 9.0 kPa', sqrt(2*9e3/(rw*(1-(0.25)**2))), sqrt(2*9e3/(rw*(1-(0.25)**2)))*A(0.04)*1000)
P('--- 例7 ピトー 60 Pa ---')
P(sqrt(2*60/1.2), sqrt(2*60/1.204))
P('jibun 150 Pa', sqrt(2*150/1.2))
P('新幹線 300 km/h 動圧', 0.5*1.2*(300/3.6)**2)
P('--- 例8 オリフィス C=0.6, beta=0.5, 15 kPa ---')
beta=0.5; C=0.6
Qo=C/sqrt(1-beta**4)*A2*sqrt(2*15e3/rw); P('Q',Qo,'L/s',Qo*1000, '比', Qo/(v2*A2))
P('jibun 差圧 2倍? 4倍で流量2倍: 60 kPa', C/sqrt(1-beta**4)*A2*sqrt(2*60e3/rw)*1000)
P('jibun 2 β=0.5 d=50mm in 100, 6.0 kPa', C/sqrt(1-beta**4)*A2*sqrt(2*6e3/rw)*1000)
P('--- 例9 噴流 板 10 m/s 2 cm2 ---')
Aj=2e-4; vj=10
P('F',rw*Aj*vj**2,'Q',Aj*vj)
P('動く板 u=4', rw*Aj*(vj-4)**2)
P('jibun 15 m/s 1 cm2', rw*1e-4*15**2, ' u=5', rw*1e-4*10**2)
P('--- 例10 消防ノズル Q=0.01 v=30 ---')
P(rw*0.01*30, 'ノズル直径', sqrt(0.01/30*4/pi)*1000,'mm')
# ホース側の速さ 65 mm
vh=0.01/A(0.065); P('ホース65mm v',vh,'正味', rw*0.01*(30-vh))
P('jibun 0.005 m3/s 25 m/s', rw*0.005*25)
P('--- 例11 曲がり管 d=0.1 3 m/s 200 kPa ---')
Ab=A(0.1); Qb=Ab*3
Fx=200e3*Ab+rw*Qb*3; P('A',Ab,'pA',200e3*Ab,'rhoQv',rw*Qb*3,'Fx',Fx,'|F|',sqrt(2)*Fx)
P('jibun d=0.05 4 m/s 300 kPa', 300e3*A(0.05)+rw*A(0.05)*16, sqrt(2)*(300e3*A(0.05)+rw*A(0.05)*16))
P('--- 例12 水力 ---')
P('力-4 の発電所', rw*g*10*100*0.85/1e6, '9.8QHη', 9.8*10*100*0.85/1000)
P('Q=100 H=50 η=0.9', rw*g*100*50*0.9/1e6)
P('jibun Q=20 H=150 η=0.88', 9.8*20*150*0.88/1000, 'MW')
P('家庭 小水力 Q=0.05 H=5 0.6', 9.8*0.05*5*0.6,'kW')
P('--- 例13 ポンプ ---')
r=0.1; n=3000; u2=2*pi*r*n/60; cu=25
P('u2',u2,'H',u2*cu/g)
P('jibun r=0.15 n=1500 cu=18', 2*pi*0.15*1500/60, 2*pi*0.15*1500/60*18/g)
P('--- 例14 スプリンクラー ---')
Qs=2e-4; an=1e-5; rr=0.15
w=(Qs/2)/an; P('w',w,'T',rw*Qs*rr*w, 'omega',w/rr,'rpm',w/rr*60/(2*pi))
P('jibun Q=3e-4 an 1.5e-5 r 0.2', (1.5e-4)/1.5e-5, rw*3e-4*0.2*10, 10/0.2, 10/0.2*60/(2*pi))
P('--- 例15 よどみ点 v=(x,-y) ---')
for (x,y) in [(1,1),(2,0.5),(0.5,2),(0,0)]:
    P(x,y,'speed',sqrt(x*x+y*y))
P('p-p0 at (1,1) rho=1000 a=1/s', -0.5*1000*2)
P('jibun v=(2x,-2y) at (1,0.5)', sqrt(4+1), -0.5*1000*(4+1))
P('--- 入試1 噴水 v0=10 m/s, 直径 2 cm ---')
v0=10; P('H',v0**2/(2*g))
for z in [2.5,4.0]:
    v=sqrt(v0**2-2*g*z); P(z,v,'d',2*sqrt(v0/v))
P('--- 入試2 台車 噴流 v=10 A=2e-4 u, M=2 kg ---')
for u in [0,2,5]: P(u, rw*2e-4*(10-u)**2, rw*2e-4*(10-u)**2/2)
P('--- 章末 ---')
P('基本 30mm→15mm 2 m/s', 2*4)
P('基本 h=3.2', sqrt(2*g*3.2))
P('基本 ピトー 水 Δp 2.0 kPa', sqrt(2*2000/1000))
P('基本 Q 5 L/s A? d=40mm', 0.005/A(0.04))
P('基本 水力 Q=5 H=30 η=0.8', 9.8*5*30*0.8)
P('チャレンジ 噴流 板 20 m/s 0.5 cm2', rw*0.5e-4*400)
P('チャレンジ ベンチュリ 120→60 Δp 20 kPa', sqrt(2*20e3/(rw*(1-1/16))), sqrt(2*20e3/(rw*(1-1/16)))*A(0.06)*1000)
P('チャレンジ タンク A=0.2 a=0.5cm2 h=0.8', 0.2/0.5e-4*sqrt(2*0.8/g))
P('チャレンジ ポンプ r=0.12 n=2400 cu=20', 2*pi*0.12*2400/60*20/g)
