# 力-12 水の中の力：圧力と浮力  例題・図・表の数値（組 P1-7）
from math import *
g = 9.8
rw = 1000.0      # 水（例題では 1000 kg/m3 とする。20 ℃で 998.2）
rsea = 1025.0    # 海水
rair = 1.204     # 空気 20 ℃ 1気圧（巻末の表）
rhe = 0.166      # ヘリウム 20 ℃ 1気圧
p0 = 101325.0
def P(*a): print(*a)

P('--- 1 圧力 ---')
# かかと 60 kg 人, 雪の上: くつ 2 足 合計 0.04 m2 と スキー 2 本 0.3 m2
m=50; F=m*g
for S,n in [(0.03,'くつ両足0.03'),(0.3,'スキー0.3'),(1e-4,'ハイヒール1cm2')]:
    P(n, F/S)
# 画びょう 10 N, 先 0.1 mm2 =1e-7 m2
P('画びょう 10N/1e-7', 10/1e-7, '頭 1 cm2', 10/1e-4)
P('--- 2 体積弾性率 ---')
K=2.2e9
P('水 1 MPa で縮む割合', 1e6/K)
P('深海 11 km 海水の圧力', rsea*g*10900/1e6, 'MPa', '縮む割合', rsea*g*10900/K)
P('空気(等温) K=p=101325 1MPa?無理; 空気 1 kPa で縮む割合', 1e3/p0)
P('K水/K空気', K/p0, K/(1.4*p0))
P('--- 3 静水圧 ---')
for h in [1,2,5,10,20,30]:
    P(h, 'm ゲージ kPa', rw*g*h/1e3, '絶対 kPa', (rw*g*h+p0)/1e3, '気圧', (rw*g*h+p0)/p0)
P('例題 水深10 m:', rw*g*10, (rw*g*10+p0), (rw*g*10+p0)/p0)
P('例題 ダイバー30 m 海水:', rsea*g*30, rsea*g*30+p0, (rsea*g*30+p0)/p0)
P('jibun 海水 20 m:', rsea*g*20, rsea*g*20+p0, (rsea*g*20+p0)/p0)
P('水道 0.2 MPa 高さ', 0.2e6/(rw*g), ' 0.3 MPa', 0.3e6/(rw*g), ' 0.15', 0.15e6/(rw*g), '0.74', 0.74e6/(rw*g))
P('--- 4 大気圧 ---')
rhg0=13595.1; rhg20=13545.9
P('水銀 0℃ 760mm', rhg0*9.80665*0.760)
P('大気圧を水柱', p0/(998.2*9.80665), p0/(1000*9.8))
P('水銀柱(9.8,13600)', p0/(13600*9.8))
P('空気 100 m で下がる圧力', rair*g*100, 'Pa; 1階3 m', rair*g*3)
P('スマホ 1.2 hPa 下がった→高さ', 120/(rair*g))
P('jibun 35 Pa →', 35/(rair*g), '600 Pa', 600/(rair*g))
P('東京スカイツリー 450 m 展望台', rair*g*450)
P('--- 5 油圧 ---')
d1, d2 = 0.01, 0.10
A1, A2 = pi*d1**2/4, pi*d2**2/4
P('面積比', A2/A1, 'F1=100N→', 100*A2/A1, 'p=', 100/A1/1e6,'MPa')
P('押す距離 10 cm → 上がる', 0.10*A1/A2*1000, 'mm')
P('jibun 2cm,12cm, 150N', 150*(0.12/0.02)**2, ' 6cm 押すと', 0.06/36*1000,'mm')
# 車 1.2 t を持ち上げる d1=2 cm d2=? F1=200 N
P('車1.2t を 200Nで:面積比', 1200*g/200, '直径比', sqrt(1200*g/200))
P('ショベル 30 MPa シリンダ 直径 0.12 m の力', 30e6*pi*0.12**2/4/1e3, 'kN', '→t', 30e6*pi*0.12**2/4/g/1000)
P('--- 6 壁の力 ---')
def wall(h,b,rho=rw): return 0.5*rho*g*h*h*b
P('ダム 100 m 幅1 m', wall(100,1)/1e6, 'MN', '圧力の中心', 2/3*100)
P('水そう 0.3 m 幅0.6 m', wall(0.3,0.6), 'N')
P('水そう 0.6 m', wall(0.6,0.6))
P('jibun ため池の板 h=2 m b=3 m', wall(2,3)/1e3, 'kN', 2/3*2)
# 傾いた水門: 鉛直深さ 3 m, 水平から60°, 幅 2 m, 上端が水面
H=3; th=radians(60); b=2
L=H/sin(th); A=L*b; hc=H/2
F=rw*g*hc*A
P('傾いた水門 L', L, 'A', A, 'F', F/1e3, 'kN', 'ycp along slant', 2/3*L, 'depth', 2/3*H)
# 数値積分（表計算）: 鉛直壁 h=3 m b=2 m 細長い帯 0.5 m ずつ
for n in [6,30,300]:
    dh=H/n; s=0; sm=0
    for i in range(n):
        hm=(i+0.5)*dh
        dF=rw*g*hm*b*dh
        s+=dF; sm+=dF*hm
    P('帯', n, s/1e3, sm/s)
P('鉛直 3m 幅2m', wall(3,2)/1e3)
# 表計算: 帯 0.5 m ずつ
P('表 鉛直壁 h=3 b=2 0.5 m の帯(中点)')
tot=0
for i in range(6):
    hm=0.25+0.5*i; p=rw*g*hm; dF=p*b*0.5; tot+=dF
    P(i, hm, p/1e3, dF/1e3, tot/1e3)
P('--- 7 浮力 ---')
# 船（鋼の箱）20×5×2, 板厚 10 mm
L,B,Hs,t = 20,5,2,0.010
Ssteel = L*B + 2*L*Hs + 2*B*Hs
ms = Ssteel*t*7850
P('鋼板面積', Ssteel, '質量', ms, 'kg', '平均密度', ms/(L*B*Hs))
P('喫水(淡水)', ms/(rw*L*B))
P('喫水 1.5 m まで積める', rw*L*B*1.5 - ms, 'kg')
P('同じ質量の鋼の塊 体積', ms/7850, '浮力', ms/7850*rw*g, '重さ', ms*g)
# jibun: 15×4×1.5 m、板厚 8 mm
L2,B2,H2,t2=15,4,1.5,0.008
S2=L2*B2+2*L2*H2+2*B2*H2; m2=S2*t2*7850
P('jibun 船 鋼', S2, m2, '喫水', m2/(rw*L2*B2), '喫水1.0mまで', rw*L2*B2*1.0-m2)
P('氷山 海水', 1-917/1025, '淡水', 1-917/1000, 'h jibun 木 500 in 水', 1-500/1000)
P('jibun 木 600 kg/m3 立方体 0.2 m: 沈む深さ', 600/1000*0.2, ' 海水', 600/1025*0.2)
# 王冠
Wa=9.80; Ww=9.16
P('王冠: 浮力', Wa-Ww, '体積', (Wa-Ww)/(rw*g)*1e6, 'cm3', '密度', Wa/(Wa-Ww)*rw)
P('純金なら V', (Wa/g)/19300*1e6, '浮力', (Wa/g)/19300*rw*g, '水中', Wa-(Wa/g)/19300*rw*g)
# 金 70% 銀 30%
V=(0.7/19300+0.3/10490); P('金70銀30 V', V*1e6, 'rho', 1/V)
# jibun: 空気中 5.00 N 水中 4.36 N
Wa2,Ww2=5.00,4.36; P('jibun 密度', Wa2/(Wa2-Ww2)*rw, '体積', (Wa2-Ww2)/(rw*g)*1e6)
Wa3,Ww3=2.70,1.70; P('jibun2 アルミ?', Wa3/(Wa3-Ww3)*rw)
# ヘリウム
P('He 1 m3 浮力', rair*g, 'He重さ', rhe*g, '差', (rair-rhe)*g, 'kg相当', rair-rhe)
P('He 20℃ 理想気体', 101325*0.0040026/(8.314462*293.15))
P('空気 20℃ 理想気体', 101325*0.028965/(8.314462*293.15))
P('jibun 風船 0.010 m3 ゴム 3 g', (rair-rhe)*0.010*1000, 'g 持ち上げ可能→ 差', (rair-rhe)*0.010*1000-3)
P('jibun 気球 何m3で60kg', 60/(rair-rhe))
# 熱気球? skip
# 台ばかり
M=2.0; m=0.27; V=100e-6
