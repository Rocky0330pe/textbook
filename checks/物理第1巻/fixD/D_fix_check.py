# 組D の直し（第19回の決定）で、変えた数・足した問題・動かした問題の検算。python3 -I で動かす。
from math import pi, sqrt
g = 9.8
rows = []
def chk(tag, text, calc, tol=0.006):
    ok = abs(calc - text) <= tol * max(abs(text), 1e-12) + 1e-12
    rows.append((tag, text, calc, ok))

# ===== 力-8 =====
# 例題2：最小二乗（Σ の書き方にしただけ。数は同じ）
sx2 = sum(x * x for x in [0.0005, 0.001, 0.0015, 0.002]); sxy = 0.0005*101 + 0.001*199 + 0.0015*302 + 0.002*398
chk("8 例2 Σx^2 (0.25+1+2.25+4)e-6", 7.5e-6, sx2); chk("8 例2 Σxy", 1.4985, sxy); chk("8 例2 E", 199800, sxy / sx2)
# D-45：理論せん断強さ G/10 と、降伏のせん断応力 σY/2
G = 79e3; chk("8 理論せん断強さ G/10 (GPa)", 8, G / 10 / 1000, 0.02)
chk("8 降伏のせん断応力 (GPa)", 0.12, 245 / 2 / 1000, 0.03); chk("8 比 約60", 60, (G / 10) / (245 / 2), 0.1)
# 章末 基本3（2）（もとチャレンジ6）・基本4（2）（もとチャレンジ4）
chk("8 基本3(2) σ", 98.4, 205000 * 1.2e-5 * 40); chk("8 基本3(2) F kN", 760, 98.4 * 7750 / 1000, 0.01)
chk("8 基本4(2) πdt", 113.1, pi * 12 * 3); chk("8 基本4(2) F kN", 28, 250 * pi * 12 * 3 / 1000, 0.02)
# 基本7（足した）：鋼の線のばね定数
A2 = pi * 2**2 / 4; k = 205000 * A2 / 1000
chk("8 基本7 k N/mm", 644, k); chk("8 基本7 比", 13000, k * 1000 / 50, 0.01)
# チャレンジ3（2）（足した小問）：ゴム ν=0.5
chk("8 チャレンジ3(2) Δd", -0.005, -0.5 * 5e-4 * 20); chk("8 チャレンジ3(2) 体積", 1.0, 1 + (1 - 2 * 0.5) * 5e-4)
# チャレンジ4（足した）：例題10の棒の両はし固定、30 K
A20 = pi * 20**2 / 4; free = 1.2e-5 * 600 * 30 + 2.3e-5 * 400 * 30
comp = 600 / (205000 * A20) + 400 / (69000 * A20); F = free / comp
chk("8 チャレンジ4 自由な伸び", 0.492, free); chk("8 チャレンジ4 0.216", 0.216, 1.2e-5*600*30); chk("8 チャレンジ4 0.276", 0.276, 2.3e-5*400*30)
chk("8 チャレンジ4 コンプライアンス", 2.78e-5, comp, 0.01); chk("8 チャレンジ4 F kN", 17.7, F / 1000, 0.01); chk("8 チャレンジ4 σ", 56, F / A20, 0.01)
# 入試にチャレンジ（けずった2問）の数（記録のため）
chk("8 けずった入試1(1)", 0.40, 60 * 0.6 / 90); chk("8 けずった入試2(1)", 4.2, 0.10 / (1.2e-5 * 2000), 0.01)

