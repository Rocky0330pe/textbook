from math import sqrt, pi, sin, cos, tan, atan, atan2, degrees, radians, log, hypot
ok = True
def chk(name, val, want, tol):
    global ok
    good = abs(val - want) <= tol
    ok &= good
    print(('OK ' if good else 'NG ') + name, round(val, 4), '期待', want)

