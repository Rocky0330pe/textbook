# 修正案で足す 力-9 入試にチャレンジ（案）：接着面の角を選んで、引ける力を最大にする
from math import tan
A_, s0, t0 = 100, 40, 20
def Fallow(th):
    c, s = cos(radians(th)), sin(radians(th))
    a = s0*A_/c**2
    b = t0*A_/(s*c) if s > 0 else float('inf')
    return min(a, b)
