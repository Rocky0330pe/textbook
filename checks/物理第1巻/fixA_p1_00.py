# 物理第1巻 第19回の直し（組A）：力-0 の数値の検算。  python3 -I fixA_p1_00.py
g = 9.8; m = 2000
T0 = m * g; T1 = m * (g + 0.50)
print("例題1 T=mg", T0, "N →2けた", round(T0 / 1000, 0), "kN（約20 kN）")
print("例題2 T=m(g+a)", T1, "N →2けた", round(T1 / 1000, 0), "kN（約21 kN）  比", round(T1 / T0, 3))
M = m * g * 10 / 1000
print("例題3 M", M, "kN·m →2けた", float('%.2g' % M), "（約200 kN·m）")
# 定規のクレーン（やってみよう）。定規30 cm・机から20 cm つき出す（重心は机のはしから5 cm 外）。
# おもり約30 g を机のはしから約8 cm 内側。定規の質量は 15〜25 g と見て、1円玉の数のはばを見る。
for mr in (15, 20, 25):
    cap = 30 * 8 - mr * 5          # 机のはしのまわりの、もどす働きの余り（g·cm）
    n10 = cap / (10 - 3); n20 = cap / (20 - 3)
    print("定規 %d g：作業半径10 cm で %.0f こ、20 cm で %.0f こ、比 %.2f（半分より少ない）" % (mr, n10, n20, n20 / n10))
# おもりがないとき（定規だけ）でも倒れないか：定規の重心は机の外 → おもりは必ず要る
print("おもりなし：もどす働き 0 − 定規の倒す働き >0 → 倒れる（本文で「おもりは十分に重く」と書いた）")
