print("==== 大気を 100 m ごとに積む（Python の囲み）")
def stack(model, dz=100.0, top=3800):
    p = P0; zz = 0.0; T0 = 15 + K; rows = []
    while zz < top - 1e-9:
        if model == 'const':
            rho = 1.2
        elif model == 'iso':
            rho = p * M / (R * T0)
        else:
            rho = p * M / (R * (T0 - L * zz))
        if abs(zz % 1000) < 1e-6:
            rows.append((zz, p))
        p = p - rho * g * dz
        zz += dz
    rows.append((zz, p))
    return rows
r1 = stack('const'); r2 = stack('iso'); r3 = stack('lapse')
for a, b, c in zip(r1, r2, r3):
    print("   z=%5.0f  %6.1f %6.1f %6.1f" % (a[0], a[1] / 1e3, b[1] / 1e3, c[1] / 1e3))
# 3776 m 近く
def stackto(model, z1, dz=100.0):
    p = P0; zz = 0.0; T0 = 15 + K
    n = int(round(z1 / dz))
    for i in range(n):
        rho = 1.2 if model == 'const' else (p * M / (R * T0) if model == 'iso' else p * M / (R * (T0 - L * zz)))
        p -= rho * g * dz; zz += dz
    return p
