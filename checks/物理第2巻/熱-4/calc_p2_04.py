print("==== 例8 音速")
pr("  20 ℃", a(293.15), "{:.1f}"); pr("  20 ℃（293 K）", a(293), "{:.1f}")
pr("  ニュートン √(R_s T)", math.sqrt(Rs * 293), "{:.1f}")
pr("  比 √1.4", math.sqrt(1.4), "{:.3f}")
pr("  0 ℃", a(273.15), "{:.1f}")
pr("  じぶんで：ヘリウム 20 ℃", a(293, 5 / 3, 2077), "{:.0f}")
pr("  章末：−20 ℃", a(253), "{:.1f}")
pr("  水 √(2.2e9/1000)", math.sqrt(2.2e9 / 1000), "{:.0f}")
for th in [-40, -20, 0, 20, 40]:
    print("   θ=%d a=%.1f" % (th, a(th + K)))

print("==== 例9 高い空")
a11 = a(216.65)
pr("  11 km 216.65 K a", a11, "{:.1f}"); pr("  250 m/s の Ma", 250 / a11, "{:.3f}")
pr("  900 km/h m/s", 900 / 3.6, "{:.1f}")
pr("  じぶんで：−50 ℃ a", a(223.15), "{:.1f}"); pr("   250 m/s の Ma", 250 / a(223.15), "{:.3f}")

print("==== 例10 よどみ点の温度")
pr("  250 m/s", 250 ** 2 / (2 * cp), "{:.1f}")
pr("  じぶんで：600 m/s", 600 ** 2 / (2 * cp), "{:.1f}")
pr("  章末：300 m/s", 300 ** 2 / (2 * cp), "{:.1f}")
pr("  100 m/s", 100 ** 2 / (2 * cp), "{:.2f}")
v2 = 2.0 * a11
