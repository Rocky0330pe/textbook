print("==== 例13 面積比")
def AoAs(Ma):
    return (1 / Ma) * ((1 + 0.2 * Ma * Ma) / 1.2) ** 3
for Ma in [2.0, 2.5, 3.0]:
    X = 1 + 0.2 * Ma * Ma
    print("   Ma=%.1f A/A*=%.3f p/p0=%.4f T/T0=%.4f" % (Ma, AoAs(Ma), X ** -3.5, 1 / X))
