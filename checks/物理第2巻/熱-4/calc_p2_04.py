import math

R = 8.314462618
M = 0.028964
Rs = 287.0        # 本文の値（R/M＝287.06）
cp = 1005.0
gam = 1.4
g = 9.8
K = 273.15
P0 = 101325.0

def pr(label, val, fmt="{:.4g}"):
    print(label, "：", fmt.format(val) if isinstance(val, (int, float)) else val)

def a(T, gm=gam, rs=Rs):
    return math.sqrt(gm * rs * T)

print("==== ② 流れの仕事・エンタルピー")
rho20 = P0 / (Rs * (20 + K))
pr("  空気 20 ℃ 1気圧の p/ρ kJ/kg", P0 / rho20 / 1e3, "{:.1f}")
pr("  R_s T kJ/kg", Rs * (20 + K) / 1e3, "{:.1f}")
pr("  c_p T（0 K から）kJ/kg", cp * (20 + K) / 1e3, "{:.1f}")
pr("  c_v T", (cp - Rs) * (20 + K) / 1e3, "{:.1f}")

print("==== ③ 3つの項の桁")
pr("  1 K の Δh kJ/kg", cp * 1 / 1e3, "{:.3f}")
pr("  Δ(v^2/2)=1 kJ/kg になる速さ m/s", math.sqrt(2 * 1000), "{:.1f}")
pr("  gΔz=1 kJ/kg になる高さ m", 1000 / g, "{:.0f}")
pr("  10 m/s の v^2/2 J/kg", 10 ** 2 / 2, "{:.0f}")
pr("  100 m/s の v^2/2 kJ/kg", 100 ** 2 / 2 / 1e3, "{:.1f}")

print("==== ④ ベルヌーイと損失")
pr("  水 損失ヘッド 10 m の温度上昇 K（c=4180）", g * 10 / 4180, "{:.4f}")
pr("  空気 1 K あたりのエネルギーと同じ水の高さ m", cp / g, "{:.0f}")

print("==== ⑤ 表計算：タンク 700 kPa・300 K からノズル")
T0 = 300.0; p0 = 700e3
rows = []
for pk in [700, 600, 500, 400, 370, 300, 200, 101.3]:
    p = pk * 1e3
    T = T0 * (p / p0) ** ((gam - 1) / gam)
    v = math.sqrt(max(0.0, 2 * cp * (T0 - T)))
    rho = p / (Rs * T)
    G = rho * v
    A = (1.0 / G * 1e4) if G > 0 else float('inf')
    rows.append((pk, T, v, rho, G, A, a(T)))
    print("   p=%6.1f T=%6.1f v=%6.1f rho=%6.3f rho*v=%7.1f A(1kg/s)=%7.2f cm2  a=%6.1f  Ma=%.2f" % (pk, T, v, rho, G, A, a(T), v / a(T)))
# 最大の G
best = max((rr for rr in rows if rr[4] > 0), key=lambda x: x[4])
pr("  ρv が最大の行の p", best[0])

print("==== 例1 ドライヤー")
pr("  1200 W・60 K g/s", 1200 / (cp * 60) * 1e3, "{:.2f}")
pr("  体積流量 L/s（20 ℃）", 1200 / (cp * 60) / rho20 * 1e3, "{:.1f}")
pr("  じぶんで：600 W・40 K g/s", 600 / (cp * 40) * 1e3, "{:.2f}")
pr("  章末：900 W・50 K g/s", 900 / (cp * 50) * 1e3, "{:.2f}")

print("==== 例2 混合水栓")
pr("  60 ℃6 L/min + 15 ℃6 L/min", (60 * 6 + 15 * 6) / 12, "{:.1f}")
pr("  じぶんで：60 ℃4 L/min + 15 ℃8 L/min", (60 * 4 + 15 * 8) / 12, "{:.1f}")

print("==== 例3 蒸気タービン")
pr("  100 kg/s × (3400−2400) MW", 100 * 1000 / 1e3, "{:.0f}")
pr("  速さ 50→100 m/s の運動エネルギーの差 kJ/kg", (100 ** 2 - 50 ** 2) / 2 / 1e3, "{:.2f}")
pr("  じぶんで：50 kg/s × (3200−2500) MW", 50 * 700 / 1e3, "{:.0f}")
pr("  章末：80 kg/s × (3300−2600) MW", 80 * 700 / 1e3, "{:.0f}")
w = 800 - (200 ** 2 - 50 ** 2) / 2 / 1e3 - 20 / 10
pr("  チャレンジ：w_出 kJ/kg（3300→2500、50→200 m/s、損失 20 kW、10 kg/s）", w, "{:.2f}")
pr("  チャレンジ：出力 MW", w * 10 / 1e3, "{:.2f}")

print("==== 例4 空気の圧縮機")
T2 = 300 * 8 ** ((gam - 1) / gam)
pr("  出口 K", T2, "{:.1f}"); pr("  w kJ/kg", cp * (T2 - 300) / 1e3, "{:.1f}")
pr("  熱-3 の式 γ/(γ−1) R_s T1 (π^…−1)", 3.5 * Rs * 300 * (8 ** (0.4 / 1.4) - 1) / 1e3, "{:.1f}")
T2j = 290 * 5 ** (0.4 / 1.4)
pr("  じぶんで：290 K・5 出口 K", T2j, "{:.1f}"); pr("   w", cp * (T2j - 290) / 1e3, "{:.1f}")
T2s = 300 * 4 ** (0.4 / 1.4)
pr("  章末：300 K・4 出口 K", T2s, "{:.1f}"); pr("   w", cp * (T2s - 300) / 1e3, "{:.1f}")
pr("  熱-3 例11 の 1 m3（20 ℃100 kPa）＝ kg", 100e3 / (Rs * 293.15), "{:.4f}")
pr("   × c_pΔT（7 倍）kJ", 100e3 / (Rs * 293.15) * cp * (293.15 * 7 ** (0.4 / 1.4) - 293.15) / 1e3, "{:.1f}")

print("==== 例5 ノズル")
pr("  Δh=100 kJ/kg m/s", math.sqrt(2 * 100e3), "{:.1f}")
pr("  じぶんで：Δh=50、入口100 m/s", math.sqrt(100 ** 2 + 2 * 50e3), "{:.1f}")
pr("  章末：Δh=200", math.sqrt(2 * 200e3), "{:.1f}")
pr("  Δh=100 のときの温度の下がり（空気）K", 100e3 / cp, "{:.1f}")

print("==== 例6 水のポンプ")
pr("  1 MPa / 998 kJ/kg", 1e6 / 998 / 1e3, "{:.3f}")
pr("  1 MPa / 1000", 1e6 / 1000 / 1e3, "{:.3f}")
pr("  全部熱なら水の温度 K", 1000 / 4180, "{:.3f}")
pr("  じぶんで：5 MPa・100 kg/s MW", 5e6 / 1000 * 100 / 1e6, "{:.2f}")

print("==== 例7 絞り弁")
pr("  密度の比 500→100 kPa", 100 / 500)
