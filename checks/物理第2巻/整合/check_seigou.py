import math

def show(label, value, text):
    print(f'{label}: {value}  （本文：{text}）')

print('== カルノーサイクル 1 mol（熱-5 例題8・熱-6 図・熱-3 例題10）')
R3, ln2 = 8.31, 0.693
QH = 1 * R3 * 600 * ln2; QL = 1 * R3 * 300 * ln2
show('熱-5 例題8 Q_H（8.31・0.693）', round(QH, 1), '3460 J')
show('熱-5 例題8 Q_L・W_出', round(QL, 1), '1730 J')
show('熱-3 例題10 nRT ln2（8.31・0.693）', round(1 * 8.31 * 300 * 0.693, 1), '約1.7 kJ（3けたで1730 J）')
show('くわしい値（8.314・ln2）', (round(8.314 * 600 * math.log(2)), round(8.314 * 300 * math.log(2))), '熱-6 図は 3460・1730 に直した（熱-5 と同じ3けた）')
show('Q/T', round(8.314 * math.log(2), 3), '5.76 J/K（熱-6 ④・熱-15）')

print('\n== ディーゼルの圧縮（熱-3 例題7・熱-7 例題1・熱-2 ⑤）')
T2 = 300 * 18 ** 0.4
show('300 K × 18^0.4', round(T2, 1), '954 K')
show('℃', round(T2 - 273, 1), '約680 ℃（熱-2 の「600 ℃をこえる」を「約680 ℃」に）')

print('\n== 空気入れ（熱-2 例題9・熱-3 例題6）')
p1, V1, T1 = 101e3, 0.20e-3, 293.0
W = p1 * V1 * (3 ** 0.4 - 1) / 0.4
show('断熱で 1/3 に押す仕事', round(W, 1), '約28 J（熱-2）')
show('ΔT = 28/(0.24e-3×718)', round(28 / (0.24e-3 * 718), 1), '約1.6e2 K（熱-2）')
show('T2 = 293×3^0.4 − 273', round(293 * 3 ** 0.4 - 273, 1), '約182 ℃（熱-3）')

print('\n== 体膨張率 β = 1/T（熱-1 ⑦ の表 → 熱-3 ②）')
show('1/293.15', f'{1 / 293.15:.3e}', '3.4×10^-3 /K')

print('\n== 窓（熱-11 ④・例題1・例題11 → 熱-9 ⑨・例題9・例題11）')
U1 = 1 / (0.11 + 0.005 / 1.0 + 0.04); U2 = 1 / (0.11 + 0.003 + 0.17 + 0.003 + 0.04)
show('1枚のガラス U', round(U1, 2), '6.5（熱-11）。熱-9 例題9 の 6.3 を 6.5 に')
show('複層ガラス U', round(U2, 2), '3.1')
q1 = 20 * U1; q2 = 20 * U2
show('表面の温度（1枚）', round(20 - q1 * 0.11, 2), '約5.8 ℃')
show('表面の温度（複層）', round(20 - q2 * 0.11, 2), '約13 ℃')
Q9 = 3 * 70 + 6.5 * 2 * 8 + 300
show('熱-9 例題9 冷房負荷', Q9, '614 W → 約0.61 kW')
show('熱-9 例題9 電力（COP 5.33）', round(Q9 / 5.33), '約115 W')
J9 = 4 * 70 + 6.5 * 3 * 7 + 200
show('熱-9 じぶんでとこう', J9, '約617 W（約0.62 kW）')

print('\n== 露点（熱-9 例題11）')
pv = 0.50 * 2.339
show('20 ℃・50 % の露点', round(9 + (pv - 1.148) / (1.228 - 1.148), 2), '約9.3 ℃')

print('\n== 大気の高さの目安（熱-3 ⑥・熱-15 例題6）')
show('空気 15 ℃', round(8.314 * 288 / (0.02896 * 9.8)), '約8.4 km')
show('窒素 15 ℃', round(8.314 * 288.15 / (0.0280 * 9.8)), '約8.7 km')
show('富士山頂の割合（窒素）', round(math.exp(-3776 / 8730), 3), '約0.65')

print('\n== 長方形のサイクル（熱-2 例題12・熱-6 図・熱-5 例題12）')
show('W_出−W_入', 200 * (3 - 1) + 100 * (1 - 3), '200 J')
show('A の物質量（200 kPa・1 L・300 K）', round(200e3 * 1e-3 / (8.314 * 300), 4), '0.080 mol（熱-6 図）')

print('\n== 熱機関の上限（熱-5 例題10：10 K 下げる・上げる）')
for name, TL, TH in [('もと', 303.15, 873.15), ('（ア）', 293.15, 873.15), ('（イ）', 303.15, 883.15)]:
    show(name, round(100 * (1 - TL / TH), 2), '65.28・66.43・65.67 %')
