p("じぶん3 ディーゼル ε=16 σ=2.5:", round(diesel(16, 2.5), 4), " (σ^γ-1)/(γ(σ-1)) =", round((2.5 ** 1.4 - 1) / (1.4 * 1.5), 4), " 1/ε^(γ-1) =", round(16 ** -0.4, 4))
