qin = cv * (T3 - T2) + cp * (T4 - T3); qout = cv * (T5 - T1)
p("例4 サバテ ε16 ξ1.5 σ1.6:", round(sabathe(e, x, s), 4), " 温度（T1=300 K）", [round(t) for t in (T2, T3, T4, T5)],
  " q_入", round(qin, 1), " q_出", round(qout, 1), " η", round(1 - qout / qin, 4))
