out = []
def p(*a): out.append(" ".join(str(x) for x in a))

def otto(e): return 1 - e ** (1 - g)
def diesel(e, s): return 1 - e ** (1 - g) * (s ** g - 1) / (g * (s - 1))
def sabathe(e, x, s): return 1 - e ** (1 - g) * (x * s ** g - 1) / ((x - 1) + g * x * (s - 1))
def brayton(r): return 1 - r ** (-(g - 1) / g)

