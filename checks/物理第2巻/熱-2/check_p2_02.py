# 例11（全微分）は記号の計算：(1) ∂y/∂y=1=∂x/∂x、(2) −1≠1
def path_int(A, B, path):
    # A(x,y), B(x,y)：数値積分（区切り 1000）
    n = 1000; s = 0.0
    for (x0, y0), (x1, y1) in zip(path[:-1], path[1:]):
        for k in range(n):
            t = (k + 0.5) / n; x = x0 + (x1 - x0) * t; y = y0 + (y1 - y0) * t
            s += A(x, y) * (x1 - x0) / n + B(x, y) * (y1 - y0) / n
    return s
