# 熱-13 光で伝わる熱：ふく射と熱交換器 の数値の検算（組 熱W7）
# 使い方: python3 c13.py
from math import exp, log, sqrt, pi
sig = 5.670374419e-8     # CODATA 2018（2022 も同じ）
b = 2897.771955           # ウィーンの変位則の定数 μm·K
K = lambda c: c + 273.15
def E(T): return sig * T**4
def p(*a): print(*a)

p('=== 本文 ②③：σT^4 と λmax（表計算の表）')
for name, T in [('氷 0℃', 273.15), ('皮膚 33℃', 306.15), ('湯 100℃', 373.15), ('なべ 300℃', 573.15),
                ('たき火のおき 1100K', 1100), ('電球 2800K', 2800), ('太陽 5772K', 5772)]:
    p('%-18s T=%7.2f  σT^4=%10.4g W/m2  λmax=%6.3f μm' % (name, T, E(T), b / T))
p('2倍：298.15→596.30 K =', 596.30 - 273.15, '℃, 比', E(596.3) / E(298.15))
p('300K の σT^4', E(300), ' 600K', E(600))

p('=== 例1 たき火：半径0.30 m の円板 1100 K、顔は正面 2.0 m')
R = 0.30
for d in (1.0, 2.0, 4.0):
    F = R**2 / (R**2 + d**2)
    p('d=%.1f F=%.4f q=%.0f W/m2  F≈R2/d2=%.4f' % (d, F, F * E(1100), R**2 / d**2))
p('比 d=2→4 :', (R**2/(R**2+4))/(R**2/(R**2+16)))
p('顔そのものの放射 33℃:', E(306.15))

p('=== 例2 太陽')
Rs, AU = 6.957e8, 1.495978707e11
p('表面', E(5772), ' 地球の所', E(5772) * (Rs / AU)**2)
p('火星 1.52 AU', E(5772) * (Rs / (1.52 * AU))**2, ' 1361/1.52^2=', 1361 / 1.52**2)
p('太陽の全放射 4πR^2σT^4 =', 4*pi*Rs**2*E(5772))

p('=== 例3 つり合いの温度')
def Teq(S, r): return (S * (1 - r) / (4 * sig))**0.25
p('地球 S=1361 r=0.30', Teq(1361, 0.30), Teq(1361, 0.30) - 273.15)
p('火星 S=589 r=0.25', Teq(589, 0.25))
p('反射率0（真っ黒）', Teq(1361, 0))
p('1層の温室：2^(1/4)Te =', 2**0.25 * Teq(1361, 0.3))
Te = Teq(1361, 0.30)
f = 2 - 2 / (288 / Te)**4
p('一部 f を吸う大気：Ts=Te(2/(2-f))^(1/4) が 288 K になる f =', f)

p('=== 例4 ウィーン')
p('太陽', b / 5772, ' 皮膚 306.15', b / 306.15, ' 電球 2800', b / 2800, ' 鉄1500', b/1500)

p('=== 例5 人と壁')
def small(eps, A, T1, T2): return eps * sig * A * (T1**4 - T2**4)
p('20℃の壁', small(0.98, 1.8, K(33), K(20)), ' 10℃', small(0.98, 1.8, K(33), K(10)))
p('基本3 板0.9 0.50 m2 80℃/20℃', small(0.9, 0.5, K(80), K(20)))

p('=== 例6 平行平板')
def pp(e1, e2, T1, T2): return sig * (T1**4 - T2**4) / (1 / e1 + 1 / e2 - 1)
p('ε0.8 500/300', pp(.8, .8, 500, 300), ' しゃへい1枚', pp(.8, .8, 500, 300) / 2)
p('しゃへい板の温度', ((500**4 + 300**4) / 2)**0.25)
p('ε0.5', pp(.5, .5, 500, 300))
p('基本4 ε0.9 と 0.1 400/300', pp(.9, .1, 400, 300), ' 黒', E(400) - E(300), ' 0.9/0.9', pp(.9,.9,400,300))
p('=== 例7 魔法びん')
p('ε0.02', pp(.02, .02, K(90), K(20)), ' 黒', E(K(90)) - E(K(20)), ' ε0.05', pp(.05, .05, K(90), K(20)))
p('分母', 1/.02+1/.02-1, 1/.05+1/.05-1)
p('=== チャレンジ6 MLI 10枚 ε0.03 300K/100K')
den = 11 * (2 / 0.03 - 1)
p('分母', den, ' q', sig * (300**4 - 100**4) / den, ' 板なし', sig * (300**4 - 100**4) / (2/0.03-1), ' 黒', sig*(300**4-100**4))

p('=== h_r')
for T in (300,):
    p('4σT^3 =', 4 * sig * T**3)
p('正確 εσ(T1^2+T2^2)(T1+T2) 306/293:', sig*(K(33)**2+K(20)**2)*(K(33)+K(20)))
p('=== 例8 放射温度計')
p(400 * (0.80 / 0.95)**0.25, '  じぶん', 500 * (0.60 / 0.95)**0.25)

p('=== 例9 LMTD')
def lm(a, c): return a if abs(a - c) < 1e-12 else (a - c) / log(a / c)
p('向流 30/30', lm(30, 30), ' 並流 70/15', lm(70, 15), ' 算術平均', (70 + 15) / 2)
p('基本5 向流 80→40,10→30: 50/30', lm(50, 30), ' 並流なら 70/10', lm(70,10))
p('じぶん 向流 hot 70→40 cold 15→35: 35/25', lm(35, 25), ' 並流 55/5', lm(55,5))

p('=== 例10・⑨ 温度効率')
def ec(N, Cr):
    if abs(Cr - 1) < 1e-12: return N / (1 + N)
    x = exp(-N * (1 - Cr)); return (1 - x) / (1 - Cr * x)
def epar(N, Cr): return (1 - exp(-N * (1 + Cr))) / (1 + Cr)
for N, Cr in [(2, .5), (4, .5), (1, .5), (2, 1), (2, 0), (4, 0), (0.5, 0.5), (3, .5), (1, 1)]:
    p('NTU=%g Cr=%g  向流 %.4f  並流 %.4f' % (N, Cr, ec(N, Cr), epar(N, Cr)))
p('向流 Cr=0.5 極限 1, 並流 Cr=0.5 極限 1/1.5=', 1/1.5)

p('=== 例11 面積')
c = 4200
Q = 0.5 * c * 40
p('Q', Q, ' A', Q / (1000 * lm(30, 30)))
c3 = 4180
p('4.18 で Q', 0.5*c3*40, ' A', 0.5*c3*40/30000)
p('じぶん 0.30 kg/s 80→40, cold 15→? 同じ流量 → 15→55; ΔT 25/25, U=800 →', 0.3*4200*40/(800*25))

p('=== チャレンジ7 NTU 法')
Ch, Cc = 0.10 * 4200, 0.20 * 4200
Cmin, Cmax = min(Ch, Cc), max(Ch, Cc)
N = 800 * 1.5 / Cmin; Cr = Cmin / Cmax
e = ec(N, Cr)
Q = e * Cmin * (80 - 15)
p('NTU', N, 'Cr', Cr, 'ε', e, 'Q', Q, 'hot out', 80 - Q / Ch, 'cold out', 15 + Q / Cc)

p('=== 例12 形態係数（球の中の球）')
r1, r2 = 0.10, 0.50
p('F21', (r1 / r2)**2, ' F22', 1 - (r1 / r2)**2)
p('じぶん 立方体の中の球？ → 半径0.2 の球が 1 辺 2.0 m の立方体の部屋：F21 =', 4*pi*0.2**2/(6*2.0**2))

p('=== 表計算：並流の熱交換器を20区間に')
Ch, Cc, UA = 2100.0, 2520.0, None
# 並流 90→60, 20→45 となる UA
UA = Ch * 30 / lm(70, 15)
p('UA', UA, 'Q', Ch * 30)
Th, Tc = 90.0, 20.0
n = 20; dUA = UA / n
rows = []
for i in range(n):
    rows.append((i, Th, Tc, Th - Tc))
    dQ = dUA * (Th - Tc)
    Th -= dQ / Ch; Tc += dQ / Cc
rows.append((n, Th, Tc, Th - Tc))
for r in rows:
    if r[0] in (0, 1, 2, 5, 10, 15, 20):
        p('%2d  Th=%.2f Tc=%.2f diff=%.2f' % r)
p('20区間：Q=', Ch * (90 - Th))
# 区間を増やすと
for n in (20, 200, 2000):
    Th, Tc = 90.0, 20.0; dUA = UA / n
    for i in range(n):
        dQ = dUA * (Th - Tc); Th -= dQ / Ch; Tc += dQ / Cc
    p('n=%d Th_out=%.3f Tc_out=%.3f' % (n, Th, Tc))
p('式：差は e^{-UA(1/Ch+1/Cc)} で減る：70*exp(..)=', 70 * exp(-UA * (1 / Ch + 1 / Cc)))
p('ΔA の比 UA/20 =', UA/20, ' 1/Ch+1/Cc=', 1/Ch+1/Cc, ' 1区間で差が何倍', 1 - UA/20*(1/Ch+1/Cc))

p('=== 表計算の表（88.2 W/K、2100、2520 で）')
Th, Tc = 90.0, 20.0
for i in range(21):
    if i in (0, 1, 2, 3, 10, 20):
        p('%2d %.2f %.2f %.2f' % (i, Th, Tc, Th - Tc))
    dQ = 88.2 * (Th - Tc); Th -= dQ / 2100; Tc += dQ / 2520
p('20区間の Q =', 2100 * (90 - 59.50))
p('2倍の面積（並流）NTU', 2*UA/2100, ' 出口差', 70*exp(-2*UA*(1/2100+1/2520)))
