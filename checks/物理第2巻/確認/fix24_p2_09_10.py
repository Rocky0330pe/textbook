from math import log, exp
from iapws import IAPWS97

print('--- 熱-9 Q4-3：20 ℃・50 % の空気の、中学の表から読む露点')
Rs = 461.5


def ps(theta):  # kPa
    return IAPWS97(T=theta + 273.15, x=0).P*1000


rho = 0.5*ps(20)*1000/(Rs*293.15)*1000  # g/m3
print('  20 ℃ 50 %% の水蒸気量 %.3f g/m3' % rho)
lo, hi = 0.0, 20.0
for _ in range(60):
    mid = (lo + hi)/2
    r = ps(mid)*1000/(Rs*(mid + 273.15))*1000
    if r < rho:
        lo = mid
    else:
        hi = mid
print('  飽和水蒸気量がこれに等しい温度 %.2f ℃' % mid)
pv = 0.5*ps(20)
lo, hi = 0.0, 20.0
for _ in range(60):
    m2 = (lo + hi)/2
    if ps(m2) < pv:
        lo = m2
    else:
        hi = m2
print('  分圧からの露点 %.2f ℃、差 %.2f K' % (m2, m2 - mid))

