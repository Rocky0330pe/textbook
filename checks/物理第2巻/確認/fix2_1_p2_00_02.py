#!/usr/bin/env python3
"""物理第2巻 確認の直し 修2-1（前付・熱-0〜2）で、変えた数・足した数の検算（第23回）。
使い方: python3 checks/物理第2巻/確認/fix2_1_p2_00_02.py
"""
from iapws import IAPWS97

ok = True


def check(name, got, want, tol):
    global ok
    good = abs(got - want) <= tol
    ok &= good
    print('%-46s %12.5g  紙面 %-10s %s' % (name, got, want, 'OK' if good else 'NG'))


# 熱-0 例題2：⑥を「≈373 s ≈ 6.2 分」の1行にまとめた
t = 1.0 * 4.2e3 * 80 / (0.90 * 1.0e3)
check('熱-0 例題2 t〔s〕', t, 373, 0.5)
check('熱-0 例題2 t〔分〕', t / 60, 6.2, 0.05)

# 熱-1 ②（Q1-18）：1気圧で水がわく温度 99.97 ℃（今の ℃ の決め方）
Ts = IAPWS97(P=0.101325, x=0).T - 273.15
check('熱-1 ② 1気圧の沸点〔℃〕（IAPWS-IF97）', Ts, 99.97, 0.005)

# 熱-1 ② 高校の教科書の T=t+273：20 ℃→約293 K、100 ℃→約373 K
check('熱-1 ② 20 ℃ を K に', 20 + 273, 293, 0)

# 熱-1 例題11 ⑥（式を別の行に出した）：1時間のガスの熱とガスの量
q_gas = 0.20 * 4.2 * 25 / 0.95          # kW
check('熱-1 例題11 ガスの熱〔kW〕', q_gas, 22.1, 0.05)
check('熱-1 例題11 1時間のガスの熱〔kJ〕', 22.1 * 3600, 79600, 50)
check('熱-1 例題11 ガスの量〔m3N/h〕', 79.6 / 45, 1.8, 0.05)

# 熱-1 まちがえやすいところ（足した）：アルミニウム 500 cm3 を 40 K
a = 2.3e-5
check('熱-1 まちがえ ×  αVΔT〔cm3〕', a * 500 * 40, 0.46, 0.005)
check('熱-1 まちがえ ○  3αVΔT〔cm3〕', 3 * a * 500 * 40, 1.4, 0.05)

# 熱-1 章末問題（入れかえただけ。数は変えていない）：7（アルミニウムの立方体）と8（メタン）
check('熱-1 章末7 (1+αΔT)^3-1', (1 + a * 200) ** 3 - 1, 0.013864, 5e-7)
check('熱-1 章末8 空気〔m3N〕', 2.0 * 2 / 0.21 * 1.1, 21, 0.5)

# 熱-1 例題12（文を詰めただけ。数は同じ）
check('熱-1 例題12 逃げる熱〔W〕', 8400 * 2.0 / 600, 28, 0)
check('熱-1 例題12 τ〔h〕', 8400 * 2.5 / 3600, 5.8, 0.05)

# 熱-2 式の読み方（括弧の位置だけ動かした）：4.184/9.8
check('熱-2 ① 4.184÷9.8〔kg〕', 4.184 / 9.8, 0.43, 0.005)

# 熱-2 例題6（鋳鉄と書きそえた。数は同じ 0.46）
check('熱-2 例題6 ΔT〔K〕', 0.5 * 1200 * 20 ** 2 / (24 * 460), 22, 0.5)

print('すべて OK' if ok else 'NG あり')
