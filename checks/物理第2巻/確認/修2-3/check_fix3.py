#!/usr/bin/env python3
"""物理第2巻 確認 Q3（熱-6〜8）の直し（修2-3）で変えた数・確かめた数の検算。
水・水蒸気は IAPWS-IF97（iapws 1.5.5）。丸めは tools/mksteam2.py（巻末の蒸気表）と同じ：h は小数1けた、
蒸発熱 L は「丸める前の h''−h'」を小数1けたに丸める。
使い方: python3 checks/物理第2巻/確認/修2-3/check_fix3.py
"""
from iapws import IAPWS97


def r1(x):
    return '%.1f' % x


def satP(p):
    return IAPWS97(P=p, x=0), IAPWS97(P=p, x=1)


print('== Q3-5 熱-8 ② 10 kPa の湿り蒸気（表の丸めた値と IF97）')
l, g = satP(0.01)
h1, h2 = 191.8, 2583.9
for x in (0.4, 0.8):
    print('  x=%.1f 表の値から %.2f → %s、IF97 %.2f → %s' % (
        x, h1 + x * (h2 - h1), r1(h1 + x * (h2 - h1)), l.h + x * (g.h - l.h), r1(l.h + x * (g.h - l.h))))
print('  増え 2105.5−1148.6 = %s、2倍 %s' % (r1(2105.5 - 1148.6), r1(2 * 1148.6)))

print('== Q3-23 蒸発熱 L（巻末の表の丸め＝丸める前の差を丸める）と、本文の「丸めた h の差」')
for p in (0.01, 0.1, 0.2, 0.5, 1, 2, 4, 10):
    l, g = satP(p)
    print("  %5g MPa  h'=%s h''=%s  巻末の L=%s  丸めた h の差=%s" % (
        p, r1(l.h), r1(g.h), r1(g.h - l.h), r1(float(r1(g.h)) - float(r1(l.h)))))
for t in (100, 200):
    l = IAPWS97(T=t + 273.15, x=0); g = IAPWS97(T=t + 273.15, x=1)
    print('  %d ℃  巻末の L=%s' % (t, r1(g.h - l.h)))

print('== Q3-20 復水器の圧力 5 kPa の飽和温度と、海水の温度あたりの飽和蒸気圧')
print('  5 kPa の飽和温度 %.2f ℃' % (IAPWS97(P=0.005, x=0).T - 273.15))
for t in (15, 25, 30, 33, 35):
    print('  %d ℃ の p_s %.3f kPa' % (t, IAPWS97(T=t + 273.15, x=0).P * 1000))

print('== Q3-22 例題9：4 MPa・s=s1 の点（IF97 の式）と、巻末の過熱蒸気表の行で s を補間した値')
s1 = IAPWS97(P=10, T=773.15).s
a = IAPWS97(P=4, s=s1)
print('  s1=%.4f  IF97: %.2f ℃, h=%.1f' % (s1, a.T - 273.15, a.h))
for (ta, tb) in ((300, 350), (350, 400)):
    A = IAPWS97(P=4, T=ta + 273.15); B = IAPWS97(P=4, T=tb + 273.15)
    sa, sb, ha, hb = round(A.s, 4), round(B.s, 4), round(A.h, 1), round(B.h, 1)
    f = (round(s1, 4) - sa) / (sb - sa)
    print('  %d〜%d ℃の行（s %.4f〜%.4f）で補間: 割合 %.3f, θ=%.1f ℃, h=%.1f' % (
        ta, tb, sa, sb, f, ta + (tb - ta) * f, ha + (hb - ha) * f))

print('== Q3-32 4 MPa の 350・450 ℃（巻末の過熱蒸気表の値）')
for t in (350, 450):
    print('  4 MPa・%d ℃  h=%s' % (t, r1(IAPWS97(P=4, T=t + 273.15).h)))

print('== Q3-32 のついで：巻末の表にない点（IF97 の式の値）')
print('  1 MPa・280 ℃  h=%s（例題12）' % r1(IAPWS97(P=1, T=553.15).h))
print('  181.3 kPa の飽和温度 %.2f ℃（じぶんでとこう13）' % (IAPWS97(P=0.1813, x=0).T - 273.15))

print('== 熱-8 ⑦に足した図（例題9 の再熱サイクルの T-s 線図）の点')
for (p, t) in ((4, 350), (4, 400), (4, 450), (4, 500)):
    print('  %g MPa・%d ℃  s=%.4f' % (p, t, IAPWS97(P=p, T=t + 273.15).s))
print('  4 MPa の飽和温度 %.2f ℃（a の 353.8 ℃は過熱蒸気）' % (IAPWS97(P=4, x=1).T - 273.15))

print('== Q3-16 熱-7 じぶんでとこう1：20 ℃・100 kPa を圧縮比16で断熱圧縮')
print('  100×16×3.03 = %.0f kPa、100×16^1.4 = %.0f kPa、T2=293×3.03=%.0f K' % (
    100 * 16 * 3.03, 100 * 16 ** 1.4, 293 * 3.03))

print('== Q3-17 で足した熱-7 ⑦の図（再生なし・理想の再生の効率と圧力比。T1=300 K、T3=1500 K）')
k = 0.4 / 1.4
for rp in (2, 5, 10, 16.72, 25, 30):
    print('  r_p=%5.2f  再生なし %.3f  理想の再生 %.3f' % (rp, 1 - rp ** -k, 1 - 300 / 1500 * rp ** k))
rc = 5 ** 1.75
print('  2本が交わる圧力比 (T3/T1)^(γ/(2(γ-1))) = %.2f、そのときの効率 %.3f（=1-1/√5）' % (rc, 1 - rc ** -k))

print('== 熱-7 ⑤に足したもっと知りたい（アトキンソンサイクル。例題9 と同じ条件）')
cp_, cv_ = 1.005, 0.718
T2a = 300 * 10 ** 0.4; T3a = T2a + 1500 / cv_; p3a = 100 * 10 * T3a / 300
T4a = T3a * (100 / p3a) ** (0.4 / 1.4); qo = cp_ * (T4a - 300)
print('  T3=%.1f K, p3=%.0f kPa, T4=%.1f K, q_出=%.1f kJ/kg, η=%.3f（オットー %.3f）、膨張比 εT4/T1=%.1f' % (
    T3a, p3a, T4a, qo, 1 - qo / 1500, 1 - 10 ** -0.4, 10 * T4a / 300))
print('  本文の丸めで：T4=2843×(100/9480)^0.2857=%.1f K、q_出=1.005×(774−300)=%.1f、η=1−476/1500=%.3f' % (
    2843 * (100 / 9480) ** 0.2857, 1.005 * 474, 1 - 476 / 1500))

print('== Q3-29 熱-7 例題9：p3')
T1, eps, cv, q = 300.0, 10, 0.718, 1500
T2 = T1 * eps ** 0.4
T3 = T2 + q / cv
print('  T2=%.2f K, T3=%.2f K, p3=p1·ε·T3/T1=%.1f kPa（T3=2843 で %.1f）' % (
    T2, T3, 100 * eps * T3 / T1, 100 * eps * 2843 / T1))
