# 例題11 の式（並べかえただけ）
for M_, w in [(0.1, 0.5), (0.3, 4.4), (0.5, 11.5)]:
    ok('例題11 Ma%.1f (%%)' % M_, (1 - (1 + 0.2 * M_ ** 2) ** -2.5) * 100, w, 0.05)
# 例題12 のチョークの流量の式
ok('例題12 0.0404 A p0/√T0 (kg/s)', 0.0404 * 1e-4 * 700000 / sqrt(300), 0.163, 0.0005)

print('== 熱-5 ==')
# Q2-15：例題10（273.15 で）
e0 = 1 - 303.15 / 873.15
eA = 1 - 293.15 / 873.15
eB = 1 - 303.15 / 883.15
ok('例題10 もと (%)', e0 * 100, 65.28, 0.005)
ok('例題10 (ア) (%)', eA * 100, 66.43, 0.005)
