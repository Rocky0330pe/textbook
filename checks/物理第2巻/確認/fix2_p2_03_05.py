# Q2-16：差しかえたチャレンジ（三角形のサイクル。kPa・L＝J）
W = 0.5 * 2 * 200
ok('チャレンジ 1周の仕事 (J)', W, 200, 0)
# A→B：p=400-100V、dQ=(3/2)d(pV)+p dV=(1000-400V)dV
Vc = 1000 / 400
ok('チャレンジ 正から負に変わる V (L)', Vc, 2.5, 0)
F = lambda V: 1000 * V - 200 * V ** 2
Qin_AB = F(Vc) - F(1)
Qout_AB = F(3) - F(Vc)
ok('チャレンジ A→B で受けとる熱 (J)', Qin_AB, 450, 0)
ok('チャレンジ A→B の後半 (J)', Qout_AB, -50, 0)
# 数で積分して確かめる
n = 200000
s_in = s_tot = 0.0
for i in range(n):
    V0 = 1 + 2 * i / n
    V1 = 1 + 2 * (i + 1) / n
    Vm = (V0 + V1) / 2
    pm = 400 - 100 * Vm
    dQ = 1.5 * ((400 - 100 * V1) * V1 - (400 - 100 * V0) * V0) + pm * (V1 - V0)
    s_tot += dQ
    if dQ > 0:
        s_in += dQ
ok('チャレンジ A→B 受けとる熱（数の和）', s_in, 450, 0.01)
ok('チャレンジ A→B 差し引き（ΔU=0, W\'=400）', s_tot, 400, 0.01)
Q_CA = 1.5 * 1 * 200
Q_BC = 2.5 * 100 * (1 - 3)
ok('チャレンジ C→A (J)', Q_CA, 300, 0)
ok('チャレンジ B→C (J)', Q_BC, -500, 0)
ok('チャレンジ 1周の熱の和＝仕事', Qin_AB + Qout_AB + Q_CA + Q_BC, 200, 1e-9)
ok('チャレンジ 熱効率', W / (Qin_AB + Q_CA), 0.27, 0.005)
ok('チャレンジ まちがい 200/700', W / 700, 0.29, 0.005)
# 時計回り（熱機関）であること：靴ひもの公式で負
