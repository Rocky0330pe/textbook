from math import log, exp, sqrt, isclose

bad = []


def ok(name, got, want, tol):
    good = abs(got - want) <= tol
    print('%-46s %12.5g  (本の値 %g)  %s' % (name, got, want, 'OK' if good else '★ずれ'))
    if not good:
        bad.append(name)


print('== 熱-3 ==')
# Q2-1：体積の比を2倍にすると、ln が ln2 だけ増える
ok('ln3', log(3), 1.10, 0.005)
ok('ln6', log(6), 1.79, 0.005)
ok('ln6-ln3 = ln2', log(6) - log(3), 0.69, 0.005)
# Q2-5：等温の大気
R, M, g = 8.31, 0.02896, 9.8
H = R * 288 / (M * g)
ok('例題5 H (m)', H, 8430, 5)
ok('例題5(2) 101.3 e^{-3776/8430} (kPa)', 101.3 * exp(-3776 / 8430), 64.7, 0.05)
# Q2-2：温度が下がる大気
L = 0.0065
base = 1 - L * 3776 / 288
ex = M * g / (R * L)
ok('例題5(3) 1-Lz/T0', base, 0.91478, 0.000005)
ok('例題5(3) Mg/(RL)（R=8.31）', ex, 5.254, 0.0005)
ok('本文⑥ Mg/(RL)（R=8.314）', M * g / (8.314 * L), 5.25, 0.005)
p3 = 101.3 * base ** ex
ok('例題5(3) p (kPa)', p3, 63.4, 0.05)
ok('例題5(3) 丸めた 0.91478^5.254 で', 101.3 * 0.91478 ** 5.254, 63.4, 0.05)
print('   （0.9148^5.25 で丸めると %.2f になり 63.5 に見えるので、5けた・4けたで書いた）' % (101.3 * 0.9148 ** 5.25))
# じぶんでとこう（2000 m）
ok('2000 m (3) 0.955^5.25', 0.955 ** 5.25, 0.785, 0.0005)
ok('2000 m (3) p', 101.3 * (1 - L * 2000 / 288) ** ex, 79.5, 0.05)
# 基本6（もとのチャレンジ9）：頂上 63.4 kPa・263.5 K
ok('基本6 袋 (mL)', 100 * 101 / 63.4 * 263.5 / 293, 143, 0.5)
ok('頂上の気温 288-24.54 (K)', 288 - L * 3776, 263.5, 0.05)
# Q2-6・U-10：ヘリウム
Rs_he = 8.314 / 0.004003
ok('ヘリウム R_s', Rs_he, 2077, 0.5)
ok('ヘリウム 20 ℃の密度', 101300 / (2077 * 293), 0.17, 0.005)
# Q2-3：差しかえたチャレンジ（N 段の圧縮機、800 kPa）
a = 0.4 / 1.4
p1V1 = 100.0  # kJ
for N, want, wr in [(1, 284, 1.811), (2, 242, 1.346), (4, 224, 1.160)]:
    r = 8 ** (a / N)
    ok('チャレンジ11 8^(a/%d)' % N, r, wr, 0.0005)
    ok('チャレンジ11 W_%d (kJ)' % N, N / a * p1V1 * (r - 1), want, 0.5)
Wiso = p1V1 * log(8)
ok('チャレンジ11 等温 100 ln8 (kJ)', Wiso, 208, 0.5)
ok('チャレンジ11 W4 は等温の何 %% 多い', (4 / a * p1V1 * (8 ** (a / 4) - 1) / Wiso - 1) * 100, 8, 0.5)
for N in [10, 100, 1000]:
    print('   N=%4d  W_N=%.2f kJ' % (N, N / a * p1V1 * (8 ** (a / N) - 1)))
# U-2 で動かした問題の数は変えていない（基本1〜5・6・7、チャレンジ8〜10）
ok('チャレンジ8 300×10^0.4 (K)', 300 * 10 ** 0.4, 754, 0.5)
ok('チャレンジ8 10^1.4', 10 ** 1.4, 25, 0.2)
ok('チャレンジ9 8/0.00975 (m)', 8 / 0.00975, 820, 1)
ok('基本7 タンク 1.87/0.120 (分)', (901000 * 0.196 / (287 * 293) - 101000 * 0.196 / (287 * 293)) / (101000 / (287 * 293) * 0.1), 16, 0.5)

print('== 熱-4 ==')
# 表3 の最後の行（101.3 kPa）
T = 300 * (101.325 / 700) ** a
v = sqrt(2 * 1005 * (300 - T))
rho = 101325 / (287 * T)
ok('表3 101.3 kPa の T', T, 172.7, 0.05)
ok('表3 101.3 kPa の v', v, 506, 0.5)
ok('表3 101.3 kPa の A (cm2)', 1 / (rho * v) * 1e4, 9.67, 0.01)
# Q2-13：圧縮機では ∫v dp = -w_t > 0（例題4 の 245 kJ/kg と同じ大きさ）
ok('例題4 ∫(1/ρ)dp = 3.5 R_s T1 ×0.811', 3.5 * 287 * 300 * 0.811 / 1000, 244, 0.5)
# U-10：ヘリウムの音速
aHe = sqrt(1.667 * 2077 * 293)
ok('じぶんでとこう8 ヘリウムの音速', aHe, 1010, 5)
print('   （理想気体の式 5/3・2077・293.15 で %.1f m/s。巻末の表は CoolProp の 1008）' % sqrt(5 / 3 * 2077 * 293.15))
# U-2 でまとめたチャレンジ（-20 ℃・128 m/s）
a253 = sqrt(1.4 * 287 * 253)
ok('チャレンジ 音の速さ (m/s)', a253, 319, 0.5)
Ma = 128 / a253
ok('チャレンジ マッハ数', Ma, 0.40, 0.005)
ok('チャレンジ 温度の上がり (K)', 128 ** 2 / 2010, 8.2, 0.05)
