import math

ok = True
def eq(name, a, b, tol=1e-9):
    global ok
    good = abs(a - b) <= tol
    ok &= good
    print(('✓' if good else '✗'), name, a, b)

# M2-01：ソラさん（0〜5分 60 m/min、5〜8分 止まる、8〜12分 100 m/min）
X = lambda t: 60 * t if t <= 5 else 300 if t <= 8 else 300 + 100 * (t - 8)
eq('M2-01 x(3)', X(3), 180); eq('M2-01 x(12)', X(12), 700); eq('M2-01 面積', 60 * 5 + 100 * 4, 700)

# M2-02：y=5x²、x=1〜1+h の変化の割合 10+5h（h=1,0.5,0.1,0.01 → 15,12.5,10.5,10.05）
for h, v in [(1, 15), (0.5, 12.5), (0.1, 10.5), (0.01, 10.05)]:
    eq(f'M2-02 h={h}', (5 * (1 + h) ** 2 - 5) / h, v, 1e-9)
# 円の接線：中心の角 60,30,10,2,0.2 → T の角 60,75,85,89,89.9
for a, b in [(60, 60), (30, 75), (10, 85), (2, 89), (0.2, 89.9)]:
    eq(f'M2-02 ∠TOP={a}', (180 - a) / 2, b, 1e-9)

# M2-03：x²+6x+10=(x+3)²+1、y=x²（−1≦x≦2）の最大4・最小0
