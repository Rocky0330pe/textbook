# M2-04：x=2t、y=5t²（0.1秒ごと）、y=1.25x²、投げ上げの頂点、噴水 10 sin2θ
for t, y in [(0.1, 0.05), (0.2, 0.20), (0.3, 0.45), (0.4, 0.80)]:
    eq(f'M2-04 5t² t={t}', 5 * t * t, y, 1e-12); eq(f'M2-04 1.25x² t={t}', 1.25 * (2 * t) ** 2, y, 1e-12)
eq('M2-04 頂点', 20 * 2 - 5 * 4, 20)
for d, x in [(15, 5), (30, 8.66), (45, 10), (60, 8.66), (75, 5)]:
    eq(f'M2-04 噴水 {d}°', round(10 * math.sin(math.radians(2 * d)), 2), x, 1e-9)

# M2-05：t²−4t+k/5=0 の判別式（15 m→4、20 m→0、25 m→−4）
for h, D in [(15, 4), (20, 0), (25, -4)]:
    eq(f'M2-05 D h={h}', 16 - 4 * h / 5, D, 1e-12)

# M2-06：pV=2000（20 mL で 100 kPa、10 mL で 200、5 mL で 400）、はかった値の pV
