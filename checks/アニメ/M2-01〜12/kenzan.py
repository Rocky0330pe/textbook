# M2-10：サイコロ3個の和の場合の数、10個の σ、30〜40 の確率
def dist(n):
    d = [1]
    for _ in range(n):
        e = [0] * (len(d) + 6)
        for i, p in enumerate(d):
            for f in range(1, 7): e[i + f] += p
        d = e
    return d
d3 = dist(3)
eq('M2-10 3個', d3[3:19] == [1, 3, 6, 10, 15, 21, 25, 27, 27, 25, 21, 15, 10, 6, 3, 1], True)
eq('M2-10 10個 σ', round(math.sqrt(10 * 35 / 12), 2), 5.40)
d10 = dist(10); eq('M2-10 30〜40', round(sum(d10[30:41]) / 6 ** 10 * 100, 1), 68.7)

# M2-11：10人の共分散 −1.76、r −0.536、5点 r 0.14、(12,12) を加えて 0.91、放物線 r 0
def r(P):
    n = len(P); mx = sum(p[0] for p in P) / n; my = sum(p[1] for p in P) / n
    sxy = sum((x - mx) * (y - my) for x, y in P); sxx = sum((x - mx) ** 2 for x, y in P); syy = sum((y - my) ** 2 for x, y in P)
    return sxy / n, sxy / math.sqrt(sxx * syy)
C = [(146, 8.5), (150, 8.6), (153, 8.9), (156, 8.2), (158, 7.8), (162, 8.2), (164, 8.2), (166, 8.8), (169, 8.1), (176, 7.7)]
cov, rr = r(C); eq('M2-11 共分散', round(cov, 2), -1.76); eq('M2-11 r', round(rr, 3), -0.536)
FIVE = [(1, 3), (2, 1), (3, 4), (4, 2), (5, 3)]
eq('M2-11 5点', round(r(FIVE)[1], 2), 0.14); eq('M2-11 6点', round(r(FIVE + [(12, 12)])[1], 2), 0.91)
eq('M2-11 放物線', r([(-2, 4), (-1, 1), (0, 0), (1, 1), (2, 4)])[1], 0)

# M2-12：ばねB S(a)=14(a−20)²+5、ばねC S=10(a−2)²+0.04、3-0 のばねの残差
