# M2-09：ふりこ20人の平均 14.20、σ 約0.108、σ/√20 約0.024
F = [14.37, 14.29, 14.24, 14.12, 14.21, 14.17, 14.33, 14.15, 14.22, 14.19, 14.16, 13.95, 14.18, 14.23, 14.16, 14.27, 14.07, 14.20, 14.44, 14.05]
