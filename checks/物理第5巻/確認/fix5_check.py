for name, Z, Qv in [('Po-212', 82, 8.954), ('U-238', 90, 4.2699)]:
    v = math.sqrt(2 * Qv / 3727)
    print(f'{name}: v/c = {v:.4f}, 2pi eta = {4*math.pi*Z/(137*v):.1f}')

