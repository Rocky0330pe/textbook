print(f'dm = {dm:.6f} u, Q = {Q:.4f} MeV, K = Q*206/210 = {Q*206/210:.4f}, 5.407*206/210 = {5.407*206/210:.4f}')

print('\n== F5-2 原-12 例題12 半減期の比（0.29 us）')
print(f'{45e8*3.16e7/0.29e-6:.3e}')

