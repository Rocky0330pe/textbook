#!/usr/bin/env python3
"""修5-4（原-9〜11 の確認の指摘 F4 の直し）で変えた数・差しかえた問題の検算。
出力は fix4_p5_09_11_out.txt。原子の質量は checks/物理第5巻/原-11/nist_masses_20261111.json（NIST AME2020、11月11日に保存）。
紙面の問題文には6けた（小数点以下6けた）に丸めた質量を書き、1 u＝931.5 MeV で計算する（原-11 の本文と同じ）。"""
import json, math, os
here = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(os.path.join(here, '..', '原-11', 'nist_masses_20261111.json')))
m = lambda k: float(M[k][0])
mn = 1.00866491595            # 中性子（CODATA 2022）
uMeV = 931.49410372
def p(*a):
    print(*a)

p('=== 原-9 ===')
p('F4-4 例題13 COP の上限 278/30 =', 278 / 30, '→ 上限なので切り捨てて 9.2')
p('F4-11 基本3 0.0259 ln(5e-3/2e-14) =', 0.0259 * math.log(5e-3 / 2e-14), ' 1000倍 0.0259 ln1000 =', 0.0259 * math.log(1000))

p('=== 原-10 ===')
p('F4-10 新しい基本4：I_C = 150 × 20 μA =', 150 * 20e-6, 'A、g_m = 0.0030/0.0259 =', 0.0030 / 0.0259, 'S')
tau = 5e3 * 0.4e-15
p('F4-10 新しい基本6：τ =', tau, 's、1段 0.69τ =', 0.69 * tau, '（ln2 で', math.log(2) * tau, '）、30段 =', 30 * 0.69 * tau, '、3 GHz の1周期 =', 1 / 3e9)
p('F4-10 チャレンジ11（1）−22×0.05 =', -22 * 0.05, '（2）', 1e4 / (1 + 1e4 / 1000), '（3）', 1e4 / (1 + 1e4 / 10), '×', 1e4 / (1 + 1e4 / 100), '=',
  1e4 / (1 + 1e4 / 10) * 1e4 / (1 + 1e4 / 100), '（4）5/65536 =', 5 / 65536 * 1e6, 'μV')
p('例題11 の段：1.25×4096/3.3 =', 1.25 * 4096 / 3.3, '（もとの 1.25/0.000806 =', 1.25 / 0.000806, 'は途中の数と合わなかった）')

p('=== 原-11 ===')
p('F4-5 太陽：水素 1 kg あたり 0.00712 × c² =', 0.00712 * 2.998e8 ** 2, 'J/kg、石炭 3e7 J/kg との比 =', 0.00712 * 2.998e8 ** 2 / 3e7)
p('F4-7 核分裂 200 MeV ÷ 水素の燃焼 3.0 eV =', 200e6 / 3.0)
p('F4-24 GPS：38 μs × c =', 38e-6 * 3.00e8, 'm、38.5 μs × c =', 38.5e-6 * 3.00e8, 'm')
p('F4-26 例題1：2.3e11 kg = ', 2.3e11 / 1e3 / 1e8, '億トン')
H, He = 1.007825, 4.002603
# 基本1：ネオン20・ケイ素28
for name, Z, A, mm in [('Ne20', 10, 20, 19.992440), ('Si28', 14, 28, 27.976927)]:
    dm = Z * H + (A - Z) * 1.008665 - mm
    dm_full = Z * m('H1') + (A - Z) * mn - m(name)
    p('F4-6 基本1', name, 'Δm =', round(dm, 6), 'u、B =', dm * 931.5, 'MeV、1核子 =', dm * 931.5 / A, '（くわしい値で', dm_full * uMeV, dm_full * uMeV / A, '）')
# 基本2：6Li + n → 3H + 4He
dq = 6.015123 + 1.008665 - 3.016049 - 4.002603
dq_full = m('Li6') + mn - m('T3') - m('He4')
p('F4-6 基本2 6Li+n→3H+4He：Δm =', round(dq, 6), 'u、Q =', dq * 931.5, 'MeV（くわしい値で', dq_full * uMeV, '）')
# 基本3：反応式の数合わせ
p('F4-6 基本3（1）235U → □ + 4He：A =', 235 - 4, 'Z =', 92 - 2, '（トリウム231）')
p('F4-6 基本3（2）27Al + 4He → □ + n：A =', 27 + 4 - 1, 'Z =', 13 + 2 - 0, '（リン30）')
p('F4-6 基本3（3）14N + n → 14C + □：A =', 14 + 1 - 14, 'Z =', 7 + 0 - 6, '（陽子）')
# 基本4：鉛208 とヘリウム4 の半径
R = lambda A: 1.2 * A ** (1 / 3)
p('F4-6 基本4 R(Pb208) =', R(208), 'fm、R(He4) =', R(4), 'fm、比 =', R(208) / R(4), '体積の比 =', 208 / 4)
# 基本5：0.1 g と 60 W
E = 0.1e-3 * 3.00e8 ** 2
p('F4-6 基本5 E =', E, 'J、60 W で', E / 60, 's =', E / 60 / 3.16e7, '年')
# チャレンジ8（新）：運動エネルギーが静止エネルギーの3倍の陽電子が、止まった電子と消える
me = 0.511
g = 4
beta = math.sqrt(1 - 1 / g ** 2)
pc = math.sqrt((g * me) ** 2 - me ** 2)
Etot = g * me + me
E1, E2 = (Etot + pc) / 2, (Etot - pc) / 2
p('F4-12 チャレンジ8（新）γ =', g, 'β =', beta, 'pc =', pc, 'MeV、全エネルギー =', Etot, 'MeV')
p('   前と後ろへ出る2本：', E1, E2, 'MeV（和', E1 + E2, '差', E1 - E2, '）、波長', 1240 / (E1 * 1e6) * 1e3, 'pm と', 1240 / (E2 * 1e6) * 1e3, 'pm')
p('   止まっているとき 0.511 MeV ずつ・', 1240 / 0.511e6 * 1e3, 'pm')

p('=== 原-9 の追加（K-17：p.412 の空きを、基本8 を足して埋めた）===')
P = 2.0 * 0.020; L = 0.30 * P; Eph = 1240 / 630
p('基本8 電力', P, 'W、光', L, 'W、光子1個', Eph, 'eV =', Eph * 1.60e-19, 'J、1秒に', L / (round(Eph, 2) * 1.60e-19), '個')
