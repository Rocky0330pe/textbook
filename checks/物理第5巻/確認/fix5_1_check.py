def chk(name, val, want, rel=0.006):
    global ok_all
    ok = abs(val - want) <= rel * abs(want)
    ok_all = ok_all and ok
    print('%-48s %-14.6g 紙面 %-10g %s' % (name, val, want, 'OK' if ok else '*** ちがう'))


