#!/usr/bin/env python3
"""物理第5巻 原-16（読みもの　原子の力とつきあう）の数値の検算（組 原W8b）。
python3 calc_p5_16.py > calc_p5_16_out.txt
出典は tex/p5-16.tex の頭のコメント。〔仮〕は見本の計算のために置いた値（本文に「とします」）。
原-15 と同じ数：200 MeV、0.0065、崩壊熱の目安の式 0.066[t^-0.2 − (t+T0)^-0.2]（t・T0 は秒、1年＝365.25日）。
原-14 と同じ数：トリチウム（水）の線量係数 0.000018 μSv/Bq、例題9（1500 Bq/L・2 L/日・365日）の 0.020 mSv、自然放射線 2.1 mSv/年。"""
import math

YEAR = 365.25 * 86400      # s（原-15 と同じ）
DAY = 86400.0
e = 1.602176634e-19        # C
NA = 6.02214076e23         # /mol
MeV = 1e6 * e


def p(label, *vals):
    out = []
    for v in vals:
        out.append(('%.4g' % v) if isinstance(v, float) else str(v))
    print(label + ':', ', '.join(out))


def ww(t, T0):
    """崩壊熱の割合 P/P0（原-15 ⑪の目安の式）。t・T0 は秒"""
    return 0.066 * (t ** -0.2 - (t + T0) ** -0.2)


print('== ① 原子の力の桁（原-15 ① と同じ数）')
E_fis = 200.0                       # MeV／分裂
E_C = 393.5e3 / NA / e              # 炭素1原子が燃えるときの eV
p('炭素1原子の燃焼 eV・200 MeV との比', E_C, E_fis * 1e6 / E_C)
m235 = 235.0439301                  # u（NIST）
E1g = NA / m235 * E_fis * MeV       # J
p('ウラン235 1 g が全部分裂 J（原-15 例題1 は 8.2e10）', E1g)
p('同じ熱を炭素（393.5 kJ/mol・12.011 g/mol）で出すときの質量 t', E1g / (393.5e3 / 12.011) / 1e6)
p('核分裂の発見（1938年の終わり）から 1945年8月まで 年', 1945 + 7.5 / 12 - (1938 + 11.5 / 12))
p('3 GW の炉が1年に分裂させるウラン235 t（原-15 例題2 の 3.2 kg/日×365.25）', 3.2 * 365.25 / 1000)
nfis = 3e9 / (E_fis * MeV)
p('3 GW：1秒の分裂の数・1年に分裂するウラン235 の質量 t', nfis, nfis * YEAR / NA * m235 / 1e6)

print('\n== ② 使い終わった燃料の崩壊熱（見本の計算1）〔仮〕3年運転・3 GW')
T3 = 3 * YEAR
for t, name in ((DAY, '1日'), (30 * DAY, '30日'), (YEAR, '1年'), (5 * YEAR, '5年'), (10 * YEAR, '10年'),
                (30 * YEAR, '30年'), (100 * YEAR, '100年')):
    p(f'{name}後：t^-0.2・(t+T0)^-0.2・割合 %・3 GW で MW', t ** -0.2, (t + T3) ** -0.2, ww(t, T3) * 100, ww(t, T3) * 3e3)
p('1年後と10年後の比', ww(YEAR, T3) / ww(10 * YEAR, T3))
p('2倍の図：運転1年と3年、1年後の割合 %（1年運転は原-15 例題12 の 0.027 %）', ww(YEAR, YEAR) * 100, ww(YEAR, T3) * 100)
p('2倍の図：運転1年と3年、10年後の割合 %', ww(10 * YEAR, YEAR) * 100, ww(10 * YEAR, T3) * 100)
p('運転6年（3年の2倍）、1年後・10年後 %', ww(YEAR, 6 * YEAR) * 100, ww(10 * YEAR, 6 * YEAR) * 100)
p('比：6年/3年 1年後・10年後', ww(YEAR, 6 * YEAR) / ww(YEAR, T3), ww(10 * YEAR, 6 * YEAR) / ww(10 * YEAR, T3))
p('止めた直後に近い 1 s（3年運転）%', ww(1, T3) * 100)
# 図の点（log-log）
for t in (DAY, 10 * DAY, 100 * DAY, YEAR, 3 * YEAR, 10 * YEAR, 30 * YEAR, 100 * YEAR):
    print('   図：t=%.4g s  P/P0=%.4g %%' % (t, ww(t, T3) * 100))

print('\n== ② もっと知りたい：t^-1.2 を運転したあいだ積分すると 5[t^-0.2 − (t+T0)^-0.2]')
for t in (1.0, DAY, YEAR, 10 * YEAR):
    n = 200000
    # 対数のきざみで数値積分（台形）
    a, b = math.log(t), math.log(t + T3)
    h = (b - a) / n
    S = 0.0
    for i in range(n + 1):
        u = a + i * h
        x = math.exp(u)
        f = x ** -1.2 * x            # d s = x d(ln x)
        S += f * (0.5 if i in (0, n) else 1.0)
    S *= h
    p(f't={t:.4g} s：数値積分・5[t^-0.2−(t+T0)^-0.2]', S, 5 * (t ** -0.2 - (t + T3) ** -0.2))
p('t≫T0 の近似 0.2 T0 t^-1.2 と、かっこの中（t=100年）', 0.2 * T3 * (100 * YEAR) ** -1.2,
  (100 * YEAR) ** -0.2 - (100 * YEAR + T3) ** -0.2)

print('\n== ③ 1000分の1になるまで（見本の計算2）')
p('1/1000 は半減期の何回分 log2(1000)・10回分で 1/1024', math.log2(1000), 1 / 2 ** 10)
p('セシウム137（約30年）：1/1000 になる年（log2）・10回分', 30 * math.log2(1000), 30 * 10)
p('プルトニウム239（約2万4千年、24110年）：1/1000 になる年', 24110 * math.log2(1000), 24110 * 10)
p('同（24100年：計画書の値）', 24100 * math.log2(1000))
p('ヨウ素131（約8日）：10回分 日（原-12 例題2 の 80日）', 8 * 10)
p('セシウム137：100年で残る割合・1/100万（20回分）の年', 0.5 ** (100 / 30), 30 * 20)
p('セシウム134（約2年）：10年で残る割合 %', 0.5 ** 5 * 100)
p('2倍の図：半減期2倍 → 1/1000 までの時間も2倍（セシウム 30→60 年で 299→598 年）', 60 * math.log2(1000))

print('\n== ③ 見本の計算3：冷やせなくなったプール〔仮〕水 1000 t・30 ℃、熱 1.5 MW（見本の計算1 の1年後）')
Pheat = ww(YEAR, T3) * 3e9
m_w = 1000e3        # kg
c_w = 4.18e3        # J/(kg·K)（原-15 ⑬・熱-1 と同じ）
L_v = 2257e3        # J/kg（100 ℃。原-15 の頭のコメント・熱-1 と同じ）
t100 = m_w * c_w * (100 - 30) / Pheat
p('熱 W・100 ℃までの時間 s・h・日', Pheat, t100, t100 / 3600, t100 / DAY)
evap = Pheat * DAY / L_v / 1000
p('100 ℃になったあと、1日に蒸発する水 t', evap)
p('1000 t が全部蒸発するまでの日数（熱は一定とみなす）', 1000 / evap)
p('10年後の熱 0.20 MW なら 100 ℃までの日数', m_w * c_w * 70 / (ww(10 * YEAR, T3) * 3e9) / DAY)
p('確かめ：2日のあいだの崩壊熱の変化（1年後と1年2日後の比）', ww(YEAR + 2 * DAY, T3) / ww(YEAR, T3))
p('崩壊熱 1日後（3年運転）で同じプール：100 ℃まで h', m_w * c_w * 70 / (ww(DAY, T3) * 3e9) / 3600)

print('\n== ⑦ 処理水とトリチウム（見本の計算4・原-14 例題9）')
k_H3 = 0.000018   # μSv/Bq（環境省 基礎資料・ICRP Publ. 119。成人・経口・水）
for c, name in ((1500, '放出の濃さの上限 1500'), (60000, '告示濃度限度 60000'), (10000, 'WHO 10000'), (30, '放出口の近く 30'),
                (1, '周辺の海 1')):
    Bq = c * 2 * 365
    p(f'{name} Bq/L を 2 L/日・365日：Bq・μSv・mSv', float(Bq), Bq * k_H3, Bq * k_H3 / 1000)
p('1500 は 60000 の何分の1・10000 の何分の1', 60000 / 1500, 10000 / 1500)
p('0.020 mSv は 2.1 mSv の何分の1', 2.1 / (1500 * 2 * 365 * k_H3 / 1000))
p('2.1 mSv の 100万分の1・7万分の1・40万分の1・10万分の1 μSv', 2.1e3 / 1e6, 2.1e3 / 7e4, 2.1e3 / 4e5, 2.1e3 / 1e5)
p('22兆 Bq を 1500 Bq/L でわった水の体積 m3（年あたりの上限の目安）', 22e12 / 1500 / 1000)
p('セシウム137 の係数 0.013 とトリチウムの比', 0.013 / k_H3)
p('まちがえやすい：1500 Bq を飲みこむ。トリチウム μSv・セシウム137 μSv（原-14 じぶんでとこう と同じ）', 1500 * k_H3, 1500 * 0.013)

print('\n== ⑥ 地域の暮らし（環境省 基礎資料・福島県の集計）')
p('避難 約16万人（2012年5月）から 22,625人（2026年5月1日）への割合 %', 22625 / 160000 * 100)
p('除去土壌の中間貯蔵施設 約1600 ha は km2', 1600 / 100)

print('\n== ⑦ 廃炉の時間')
p('事故（2011年）から廃止措置の目標 2041〜2051 年まで 年', 2041 - 2011, 2051 - 2011)
p('汚染水 540 → 70 m3/日：何分の1', 540 / 70)
