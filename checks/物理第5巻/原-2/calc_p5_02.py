def p(label, *v):
    print(label + ': ' + ', '.join(f'{x:.5g}' if isinstance(x, float) else str(x) for x in v))


def Eb(lam, T):   # 黒体の単色放射の強さ W/(m2·m)
    return 2 * pi * h * c ** 2 / lam ** 5 / (math.exp(h * c / (lam * kB * T)) - 1)


def trap(f, a, b, n):
    s = 0.5 * (f(a) + f(b)); dx = (b - a) / n
    for i in range(1, n):
        s += f(a + i * dx)
    return s * dx


