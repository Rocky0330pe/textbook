# 原-2 例題1の囲みのプログラム（紙面と同じ）。黒体の光のうち、目に見える光（380〜780 nm）の割合を、
# 10 nm ごとの台形の和（5-10）で求める。
from math import exp, pi
h, c, k = 6.626e-34, 2.998e8, 1.381e-23    # プランク定数・光速・ボルツマン定数
sigma = 5.670e-8                            # シュテファン・ボルツマン定数
def E(lam, T):                              # 単色放射の強さ（W/m^2 を 1 m あたり）
    return 2 * pi * h * c**2 / lam**5 / (exp(h * c / (lam * k * T)) - 1)
for T in [1000, 1500, 2800, 5772]:
    vis = 0.0
    for i in range(40):                     # 380〜780 nm を 10 nm ずつ 40 本
        a = 380e-9 + i * 10e-9
        vis = vis + (E(a, T) + E(a + 10e-9, T)) / 2 * 10e-9   # 台形の面積
    print(T, round(2.898e-3 / T * 1e6, 2), '%.2g' % (vis / (sigma * T**4) * 100))
