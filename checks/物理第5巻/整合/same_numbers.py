#!/usr/bin/env python3
"""物理第5巻 整合の組（11月）：計画書 C-4 の「同じ題材の数をそろえる」の数を、章をまたいで計算し直す。
各章の本文の値（右の欄）と合っているかを並べる。値は CODATA 2022・NIST（計画書 C-3）。
"""
import math

h = 6.62607015e-34; c = 299792458; e = 1.602176634e-19; kB = 1.380649e-23
me = 9.1093837139e-31; NA = 6.02214076e23; mec2 = 0.51099895069  # MeV

rows = []
def row(name, val, text, where):
    rows.append((name, val, text, where))

hc = h * c / e * 1e9
row('hc〔eV·nm〕', hc, '1240', '原-2・4・5・9・13 ほか')
kT = kB * 300 / e
row('300 K の kT〔eV〕', kT, '0.0259（原-9 例題2 だけ 0.02585）', '全章')
row('熱-15：e^(-0.1/kT)', math.exp(-0.1 / 0.0259), '0.021', '原-4・7・8')
# 0.662 MeV のγ線のコンプトン散乱
E = 0.662
for th in (90, 180):
    Ep = E / (1 + E / mec2 * (1 - math.cos(math.radians(th))))
    row('0.662 MeV、%d° の γ線〔MeV〕' % th, Ep, '0.288' if th == 90 else '0.184', '原-2 例題10・原-11 例題10・原-13 ④')
    row('  同じく電子〔MeV〕', E - Ep, '0.374' if th == 90 else '0.478（コンプトン端）', '原-2 例題10・原-11 例題10・原-13 ④')
# 銅の自由電子
n_cu = 8.96e6 / 63.55 * 6.02e23
row('銅の自由電子 n〔1/m³〕', n_cu, '8.49e28', '原-7 例題8・原-8')
# 幅 1 nm の箱
E1 = h ** 2 / (8 * me * (1e-9) ** 2) / e
row('幅 1 nm の箱の E1〔eV〕', E1, '0.376', '原-5・6・8')
row('ħ²/(2m)〔eV·nm²〕', (h / 2 / math.pi) ** 2 / (2 * me) / e * 1e18, '0.0381', '原-5・6')
# ケイ素
row('ケイ素 1.12 eV の波長〔nm〕', 1240 / 1.12, '1110', '原-2 例題6・原-8・原-9')
# ダイオード（原-9・10）
Is = 1e-14; VT = 0.0259
row('1 mA の電圧〔V〕', VT * math.log(1e-3 / Is), '0.66', '原-9 例題8')
row('10倍の電圧〔mV〕', VT * math.log(10) * 1e3, '59.6', '原-9 例題8・原-10')
V = 0.7
for _ in range(10):
    f = Is * (math.exp(V / VT) - 1) - (5 - V) / 1000
    fp = Is / VT * math.exp(V / VT) + 1 / 1000
    V -= f / fp
row('5 V・1 kΩ・ダイオードの電圧〔V〕', V, '0.694', '原-10 ⑫・例題12')
row('  同じく電流〔mA〕', (5 - V) / 1000 * 1e3, '4.31', '原-10 ⑫・例題12')
row('g_m（1 mA）〔mS〕', 1e-3 / VT * 1e3, '38.6', '原-10 ③・例題3')
# 炭素14・親と子
row('炭素14 の τ〔年〕', 5730 / math.log(2), '8270', '原-12、数学 6-4')
t = math.log(1 / 1 / (1 / 2)) / (1 / 1 - 1 / 2)
N2 = 1000 * (1 / 2) / (1 - 1 / 2) * (math.exp(-t / 2) - math.exp(-t / 1))
row('親と子（2 h・1 h・1000）の山の時刻〔h〕', t, '1.39', '原-12 ⑧・例題7、数学 6-14')
row('  同じく子の数', N2, '250', '原-12 ⑧・例題7')
# 電-6 例題8 の装置（原-1 例題3）
em = e / me
r = math.sqrt(2 * 1000 / em) / 1e-3
row('1.0 kV・1.0 mT の半径〔cm〕', r * 100, '10.66（電-6 は 0.11 m）', '原-1 例題3')
row('  0.11 m で求めた e/m のずれ〔%〕', ((r / 0.11) ** 2 - 1) * 100, '−6', '原-1 例題3')
# 中性子の減速（原-13・15）
L = math.log(2e6 / 0.025)
for name, A in (('水素', 1), ('炭素', 12)):
    a = ((A - 1) / (A + 1)) ** 2
    xi = 1 if A == 1 else 1 + a * math.log(a) / (1 - a)
    row('2 MeV→0.025 eV、%s の回数' % name, L / xi, '18' if A == 1 else '115', '原-13 ⑥・例題10、原-15')
row('水の熱中性子の道のり〔cm〕', 1 / (2 * 3.34e22 * 0.332e-24), '45', '原-13 例題11')
# ウラン235 の分裂・遅発中性子
row('U-235 の分裂の Q 値〔MeV〕', 931.5 * ((235.043930 + 1.008665) - (140.914403 + 91.926173 + 3 * 1.008665)), '173（β崩壊を足して約200）', '原-11 例題3・原-15')
row('β（遅発中性子の割合）', 0.0065, '0.0065', '原-15（原-16 も）')
# 計数のばらつき
row('100 個の √N', math.sqrt(100), '10', '原-12 ⑨・原-14 ③')
row('1000 個の √N', math.sqrt(1000), '32', '原-12 ⑨・原-14 ③')
# 止めたあとのキセノン（原-15 ⑩・例題11）
lI, lX = math.log(2) / 6.58, math.log(2) / 9.14
r0 = 0.064 / 0.0664 * (lX + 2.6e-18 * 3e13 * 3600) / lI  # 原-15 例題11 の I0/X0（3.26。出典の組が IAEA の値に直した）
ts = [k / 1000 for k in range(1, 48000)]
xs = [math.exp(-lX * t) + r0 * lI / (lX - lI) * (math.exp(-lI * t) - math.exp(-lX * t)) for t in ts]
k = max(range(len(xs)), key=lambda i: xs[i])
row('キセノン135 の山（時刻〔h〕）', ts[k], '8.3', '原-15 図（⑩）・例題11')
row('  同じく高さ', xs[k], '1.88（原-15 の検算は 1.881）', '原-15 図（⑩）・例題11')

for name, val, text, where in rows:
    print('%-36s %12.5g   本文 %-28s %s' % (name, val, text, where))
