# 物理第5巻 原-1（tex/p5-01.tex）の数値の検算（組 原W1）。python3 calc_p5_01.py > calc_p5_01_out.txt
# 定数は CODATA 2022（NIST allascii.txt）。本文の丸め：e=1.60e-19、m_e=9.11e-31、k=8.99e9、ke^2=1.44 MeV·fm、g=9.8。
import math
pi = math.pi
e = 1.602176634e-19; me = 9.1093837139e-31; u = 1.66053906892e-27; NA = 6.02214076e23
F = 96485.33212; alpha = 7.2973525643e-3; hbarc = 197.3269804; ke2 = alpha * hbarc   # MeV fm
em_codata = 1.75882000838e11
er, mer, g = 1.60e-19, 9.11e-31, 9.8   # 本文の丸め


def p(label, *v):
    print(label + ': ' + ', '.join(f'{x:.5g}' if isinstance(x, float) else str(x) for x in v))


print('== 定数');
p('ke2 MeV fm', ke2); p('e/m CODATA', em_codata); p('e/m 丸め', er / mer)

print('== はてな・例題1：金の原子核と原子')
# 金：モル質量 196.966570 g/mol（NIST）、密度 19.32 g/cm3（NIST XrayMassCoef 表1）、面心立方（4個/格子）
M_Au, rho_Au = 196.966570e-3, 19.32e3
aAu = (4 * M_Au / (rho_Au * NA)) ** (1 / 3)
rAu = aAu * math.sqrt(2) / 4
p('金の格子定数 nm・原子の半径（となりとの間の半分）nm', aAu * 1e9, rAu * 1e9)
RAu = 1.2 * 197 ** (1 / 3)
p('原子核の半径 1.2A^(1/3) fm', RAu)
ratio = RAu * 1e-15 / 0.144e-9
p('長さの比・体積の比・逆数', ratio, ratio ** 3, 1 / ratio, 1 / ratio ** 3)
p('原子 100 m のとき原子核 mm', 100 * ratio * 1e3)
print('-- じぶんでとこう1：水素（陽子 0.84 fm、ボーア半径 0.0529 nm）')
rp, a0 = 0.84075e-15, 5.29177210544e-11
p('長さの比・体積の比', rp / a0, (rp / a0) ** 3)
p('原子 100 m のとき陽子 mm', 100 * rp / a0 * 1e3)
p('丸めた値 0.84/0.0529e6', 0.84e-15 / 0.0529e-9)
p('質量の割合：金の原子核/原子（電子79個）', 1 - 79 * 9.109e-31 / (196.966570 * u))

print('== 例題2：トムソン（E=2.0e4、B=1.0 mT、r=0.114 m）')
E, B = 2.0e4, 1.0e-3
v = E / B
r_true = me * v / (e * B)
p('v m/s・本当の r m', v, r_true)
p('r=0.114 から e/m', v / (0.114 * B))
p('e/m = E/(B^2 r)', E / (B ** 2 * 0.114))
p('今の値との差 %', (v / (0.114 * B) / em_codata - 1) * 100)
print('-- じぶんでとこう2：E=3.0e4、B=2.0 mT')
E2, B2 = 3.0e4, 2.0e-3
v2 = E2 / B2; r2 = me * v2 / (e * B2)
p('v・本当の r', v2, r2)
p('r=0.0427 から e/m', v2 / (0.0427 * B2))

print('== 例題3：電-6 例題8 と同じ数 1.0 kV・1.0 mT')
V, B = 1000.0, 1.0e-3
vv = math.sqrt(2 * e * V / me); rr = me * vv / (e * B)
p('v・r m', vv, rr)
p('r=0.1066 m から e/m=2V/(B^2r^2)', 2 * V / (B ** 2 * 0.1066 ** 2))
p('差 %', (2 * V / (B ** 2 * 0.1066 ** 2) / em_codata - 1) * 100)
p('r=0.11（2けた）なら', 2 * V / (B ** 2 * 0.11 ** 2))
p('v/c', vv / 299792458)
print('-- じぶんでとこう3：500 V・1.0 mT')
rr5 = math.sqrt(2 * 500 * me / e) / 1e-3
p('本当の r', rr5)
p('r=0.0754 から e/m', 2 * 500 / (1e-6 * 0.0754 ** 2))

print('== 例題4：ミリカン（半径 1.0 μm、密度 870、極板 5.0 mm）')
r0, rho, d = 1.0e-6, 870.0, 5.0e-3
m = 4 / 3 * pi * r0 ** 3 * rho
p('質量 kg・重さ N', m, m * g)
for n in (1, 2, 3):
    p(f'電荷 {n}e：電圧 V（e=1.60e-19）', m * g * d / (n * er))
p('浮力の割合（空気 1.2 kg/m3）', 1.2 / 870)
print('-- じぶんでとこう4：半径 0.80 μm、極板 4.0 mm、電荷 2e')
m4 = 4 / 3 * pi * (0.80e-6) ** 3 * rho
p('質量・電圧', m4, m4 * g * 4.0e-3 / (2 * er))

print('== 例題5：ミリカンのデータ')
for q in (3.2, 4.8, 8.0, 11.2):
    p(f'{q}e-19 / 1.6', q / 1.6)
print('-- じぶんでとこう5')
for q in (6.4, 9.6, 14.4, 17.6):
    p(f'{q}/1.6 と /3.2', q / 1.6, q / 3.2)

print('== 例題6：油滴が 1.0 mm を 9.6 s で落ちる')
