vt = 1.0e-3 / 9.6
r6 = math.sqrt(9 * eta * vt / (2 * rho * g))
p('v m/s・r μm', vt, r6 * 1e6)
p('r=1.0 μm の終端速度', 2 * (1e-6) ** 2 * rho * g / (9 * eta))
p('終端速度に近づく時定数 s m/(6πηr)', m / (6 * pi * eta * 1e-6))
print('-- じぶんでとこう6：2.0 mm を 4.8 s')
vt2 = 2.0e-3 / 4.8
p('v・r μm', vt2, math.sqrt(9 * eta * vt2 / (2 * rho * g)) * 1e6)

print('== 例題7：銀の電気分解（0.500 A × 1930 s、銀 1.079 g、107.87 g/mol）')
Q = 0.500 * 1930
nAg = 1.079 / 107.87
p('電荷 C・銀 mol・F C/mol', Q, nAg, Q / nAg)
p('N_A = F/e（e=1.60e-19）', Q / nAg / er)
p('N_A = 96485/1.602176634e-19', F / e)
print('-- じぶんでとこう7：銅 Cu2+ 1.00 A × 3600 s、1.185 g、63.55 g/mol')
nCu = 1.185 / 63.55
