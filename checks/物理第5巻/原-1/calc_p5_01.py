print('== 例題11：0.40 μm の金箔で 90°より大きく曲がる割合')
nAu = 19.32e3 / 196.97e-3 * 6.02e23
b90 = d / 2 * 1e-15
frac = nAu * 0.40e-6 * pi * b90 ** 2
p('数密度・b90 m・πb^2 m2・割合・逆数', nAu, b90, pi * b90 ** 2, frac, 1 / frac)
