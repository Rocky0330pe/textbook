import math


def p(label, *vals):
    s = ", ".join(f"{v:.4g}" if isinstance(v, float) else str(v) for v in vals)
    print(f"{label}: {s}")


year_h = 365.25 * 24
print("== ③ 数え落とし（例題1）")
m = 30000 / 60
tau = 100e-6
n = m / (1 - m * tau)
p("計数率 m /s・真の n /s・数え落とし %", m, n, (n - m) / n * 100)
for mm in (50, 100, 500, 1000, 2000, 5000):
    nn = mm / (1 - mm * tau)
    p(f"  m={mm}：n・数え落とし %", nn, (nn - mm) / nn * 100)
p("じぶん1：m=2000 /s の n", 2000 / (1 - 2000 * tau))
p("真の n が限りなく大きくても m は 1/τ をこえない：1/τ", 1 / tau)
print("== ③ 計数のばらつき")
for N in (100, 400, 1000, 10000):
    p(f"  N={N}：σ・割合 %", math.sqrt(N), 100 / math.sqrt(N))
p("4倍の時間で割合は 1/2", 1 / math.sqrt(4))

print("== ④ 吸収線量（例題2）")
p("60 kg に 1 Gy：J・温度 K", 60.0, 1 / 4180)
p("じぶん2：水 1 kg に 10 Gy の温度 K", 10 / 4180)
p("1 Gy のエネルギーで作る電離（34 eV）の数 /kg", 1 / (34 * 1.602e-19))
p("体重 60 kg が 1 Gy：電離の数", 60 / (34 * 1.602e-19))

print("== ⑤ 等価線量・実効線量（例題3・4）")
p("α 1 mGy → mSv", 1 * 20)
p("γ 1 mGy → mSv", 1 * 1)
p("甲状腺 10 mSv × 0.04 → mSv", 10 * 0.04)
wT = {'骨髄': 0.12, '結腸': 0.12, '肺': 0.12, '胃': 0.12, '乳房': 0.12, '残り': 0.12, '生殖腺': 0.08,
      '膀胱': 0.04, '食道': 0.04, '肝臓': 0.04, '甲状腺': 0.04, '骨表面': 0.01, '脳': 0.01, '唾液腺': 0.01, '皮膚': 0.01}
p("組織加重係数の合計", sum(wT.values()))
p("じぶん3：中性子 2 mGy（w_R=10 とする）→ mSv", 2 * 10)
p("じぶん4：肺 5 mSv・胃 2 mSv の実効線量 mSv", 5 * 0.12 + 2 * 0.12)

print("== ⑥ 点線源（例題5・6・11）")
Gam = 0.0927  # μSv m²/(MBq h)
for r in (0.5, 1, 2, 3):
    p(f"Cs-137 1 MBq・{r} m：μSv/h", Gam / r ** 2)
# 空気カーマを NIST の μen/ρ で計算（物理量）
muen = math.exp(math.log(0.02953) + (math.log(0.02882) - math.log(0.02953)) * (math.log(0.662) - math.log(0.6)) / (math.log(0.8) - math.log(0.6)))
phi = 1e6 * 0.85 / (4 * math.pi * 100 ** 2)  # 1/(cm² s) at 1 m
K = phi * 0.662 * muen * 1.602176634e-13 * 1e3 * 3600 * 1e6  # μGy/h
p("空気の μen/ρ(0.662) cm²/g・1 m の光子の流れ 1/(cm² s)・空気カーマ率 μGy/h", muen, phi, K)
p("1 cm 線量当量率定数 / 空気カーマ率定数", Gam / K)
mPb = 0.1111 * 11.35
D6 = 37 * Gam / 2 ** 2 * 0.5 * math.exp(-mPb * 1)
p("例題6：37 MBq・2 m・30 分・鉛 1 cm：遮へいなし μSv/h・鉛の透過・μSv", 37 * Gam / 4, math.exp(-mPb), D6)
p("例題6：距離 1 m・遮へいなし・1時間なら μSv", 37 * Gam / 1 * 1)
p("例題6：3原則の効果 (1m,1h,なし)/(2m,0.5h,鉛)", (37 * Gam) / D6)
p("じぶん6：鉛 2 cm にしたら μSv", 37 * Gam / 4 * 0.5 * math.exp(-2 * mPb))
for d, a in ((10, 2), (5, 2), (2, 2), (20, 2)):
    exact = 0.5 * (1 - d / math.sqrt(d * d + a * a))
    approx = a * a / (4 * d * d)
    p(f"例題11 検出器半径 {a} cm・距離 {d} cm：Ω/4π・近似 a²/4d²", exact, approx)
p("じぶん11：検出器 半径 2 cm を 10 cm で 1000 Bq（γ 1本ずつ）：入る数 /s", 1000 * 0.5 * (1 - 10 / math.sqrt(104)))

print("== ⑦ 3原則の2倍の図")
for r in (1, 2, 3, 4):
    p(f"  距離 {r}：1/r²", 1 / r ** 2)

print("== ⑩ 自然放射線（例題7）")
p("2.1 mSv/年 → μSv/h", 2.1e3 / year_h)
p("2.4 mSv/年 → μSv/h", 2.4e3 / year_h)
p("外部被ばく（宇宙 0.3＋大地 0.33）mSv/年 → μSv/h", 0.63, 0.63e3 / year_h)
nat = {'宇宙線': 0.3, '大地': 0.33, 'ラドン222': 0.37, 'ラドン220': 0.09, '喫煙': 0.006, 'その他吸入': 0.006,
       '鉛210・ポロニウム210': 0.80, 'トリチウム': 0.0000049, '炭素14': 0.014, 'カリウム40': 0.18, '温泉など': 0.005, '航空機': 0.008}
p("内訳の合計 mSv/年", sum(nat.values()))
p("吸入の合計・経口の合計", 0.37 + 0.09 + 0.006 + 0.006, 0.80 + 0.0000049 + 0.014 + 0.18)
p("医療 2.6 と合わせて mSv/年", 2.1 + 2.6)
p("0.1 μSv/h に 1年いる mSv", 0.1 * year_h / 1e3)
p("じぶん7：0.05 μSv/h に 8 時間/日・1年（365日）mSv", 0.05 * 8 * 365 / 1e3)

print("== ⑧ 内部被ばく（例題8・9）")
p("100 Bq/kg × 1 kg × 0.013 μSv/Bq：μSv", 100 * 1 * 0.013)
p("じぶん8：10 Bq/kg の飲料水を1日 2 L・1年（Cs-137）μSv", 10 * 2 * 365 * 0.013)
p("トリチウム 1500 Bq/L × 2 L × 365 × 0.000018：μSv・mSv", 1500 * 2 * 365 * 0.000018, 1500 * 2 * 365 * 0.000018 / 1000)
p("じぶん9：同じ水 1 L に入っているセシウム137 がもし 1500 Bq なら（比較）μSv/L", 1500 * 0.013)
p("トリチウムとセシウム137 の係数の比", 0.013 / 0.000018)
p("カリウム40：体内（60 kg で約 4000 Bq〔使わない〕）", "-")

print("== ⑨ 検出限界（例題10）")
B = 30
t = 10
NB = B * t
sig_rate = math.sqrt(NB) / t
p("背景 30 cpm・10 分：数 N・σ（数）・σ（cpm）・3σ cpm", NB, math.sqrt(NB), sig_rate, 3 * sig_rate)
p("1分だけはかると σ・3σ cpm", math.sqrt(30), 3 * math.sqrt(30))
p("40 分なら 3σ cpm（4倍の時間で 1/2）", 3 * math.sqrt(30 * 40) / 40)
p("じぶん10：背景 100 cpm・4 分：σ・3σ cpm", math.sqrt(400) / 4, 3 * math.sqrt(400) / 4)
p("正規分布で 3σ をこえる片側の確率 %", 0.5 * math.erfc(3 / math.sqrt(2)) * 100)

print("== ⑫ 線量限度（例題12）")
p("20 mSv を 10 μSv/h：時間 h", 20e3 / 10)
p("50 mSv を 10 μSv/h：時間 h", 50e3 / 10)
p("管理区域 1.3 mSv/3月 を 1週40時間×13週で：μSv/h", 1.3e3 / (40 * 13))
p("じぶん12：女性 5 mSv/3月 を 10 μSv/h：時間 h", 5e3 / 10)
p("一般公衆 1 mSv/年 を 1年中：μSv/h", 1e3 / year_h)

print("== ⑪ LNT（例題13）")
p("1000 人・100 mSv・0.5 %：人", 1000 * 0.005)
p("じぶん13：10 万人が 10 mSv（LNT）：人", 1e5 * 0.005 * 10 / 100)
p("1000 人が 1 mSv（LNT）：人", 1000 * 0.005 * 1 / 100)

print("== 空気の減弱（モデル化の札）")
mu_air = math.exp(math.log(0.08055) + (math.log(0.07074) - math.log(0.08055)) * (math.log(0.662) - math.log(0.6)) / (math.log(0.8) - math.log(0.6))) * 1.205e-3
p("空気 0.662 MeV：μ 1/cm・10 m で減る割合", mu_air, 1 - math.exp(-mu_air * 1000))
