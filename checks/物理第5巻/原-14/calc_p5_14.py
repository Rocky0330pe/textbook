p("チャレンジ2：検出器 a=1 cm を d=1 cm：Ω/4π・逆2乗の近似", 0.5 * (1 - 1 / math.sqrt(2)), 1 / 4)
# チャレンジ3：数え落としの補正の τ を2つの計数率から（2線源法の考え方は扱わず、m と n から τ）
