"""原-0（序章）の数値の検算。python3 calc_p5_00.py > calc_p5_00_out.txt
定数：CODATA 2022（NIST allascii.txt）。アルミの標準原子量 26.9815385・密度 2.699 g/cm3：NIST（Atomic Weights / XrayMassCoef 表1）。
1円玉：通貨の単位及び貨幣の発行等に関する法律施行令 別表第一（純アルミニウム・1グラム・直径20ミリメートル）。
炭素の燃焼：CO2 の生成エンタルピー −393.51 kJ/mol（NIST Chemistry WebBook）。月までの距離 384400 km（NASA Moon Fact Sheet：力-6 と同じ）。"""
import math
NA = 6.02214076e23; e = 1.602176634e-19; a_Si = 0.5431020511e-9
print("== 例題1：1円玉")
m, M, rho = 1.00, 26.9815385, 2.699          # g, g/mol, g/cm3
N = m / M * NA
print("原子の数 N = %.4e 個" % N)
V = m / rho                                   # cm3
v = V / N * 1e-6                              # m3
a = v ** (1/3)
print("体積 V = %.4f cm3、1個の体積 v = %.4e m3、1辺 a = %.4f nm" % (V, v, a*1e9))
Nr = 1/27.0*6.02e23
print("丸めた値で：1.00/27.0*6.02e23 = %.3e、1.00/2.70 = %.4f cm3、v = %.3e m3、a = %.3f nm" % (
    Nr, 1/2.70, 1/2.70/Nr*1e-6, (1/2.70/Nr*1e-6)**(1/3)*1e9))
v2 = 27.0 / (2.70 * 6.02e23) * 1e-6
print("M/(rho NA) = %.4e m3 → a = %.4f nm" % (v2, v2**(1/3)*1e9))
L = N * a                                     # m
print("1列：%.3e m = %.3e km、月まで 384400 km の %.0f 倍" % (L, L/1e3, L/1e3/384400))
L2 = 2.2e22 * 0.26e-9
print("丸めた値で 2.2e22×0.26e-9 = %.3e m = %.2e km、月の %.0f 倍" % (L2, L2/1e3, L2/1e3/384400))
print("光の速さで 1列を進む時間：%.0f s = %.1f 時間" % (L/2.998e8, L/2.998e8/3600))
print("2倍：1辺2倍 → 1個の体積8倍 → 数 1/8：%.3e" % (N/8))
print("1円玉の平均の厚さ（体積÷円の面積、半径1.0 cm）：%.3f cm" % (V / (math.pi*1.0**2)))
print("== 例題2：燃える（炭素）と分かれる（ウラン235）")
dH = 393.5e3                                   # J/mol
Ec = dH / NA
print("炭素1個 %.4e J = %.3f eV" % (Ec, Ec/e))
print("丸めた値で 393.5e3/6.02e23 = %.3e J、÷1.60e-19 = %.3f eV" % (393.5e3/6.02e23, 393.5e3/6.02e23/1.60e-19))
Ef = 200e6
print("分裂/燃焼（1個あたり） = %.3e 倍、200e6/4.1 = %.3e" % (Ef/(Ec/e), 200e6/4.1))
Ekg_c = dH / 12.011e-3
Ekg_u = 1000/235.0439301*NA*Ef*e
print("1 kg：炭素 %.3e J、ウラン235 %.3e J、比 %.3e" % (Ekg_c, Ekg_u, Ekg_u/Ekg_c))
Ekg_u2 = 1000/235*6.02e23*200e6*1.60e-19
Ekg_c2 = 1000/12.0*393.5e3
print("丸めた値で：炭素 1000/12.0×393.5 kJ = %.3e J、ウラン 1000/235×6.02e23×200 MeV = %.3e J、比 %.3e" % (Ekg_c2, Ekg_u2, Ekg_u2/Ekg_c2))
print("1 kg の原子の数：炭素 %.3e、ウラン %.3e、比 %.2f" % (1000/12.0*6.02e23, 1000/235*6.02e23, 235/12.0))
print("4.9e7 / 19.6 = %.3e" % (4.9e7/19.6))
print("1 eV = %.10e J" % e)
print("== 例題3：10 nm の線にケイ素の原子")
d = math.sqrt(3)*a_Si/4
print("となりの原子の間（結合の長さ）√3a/4 = %.4f nm" % (d*1e9))
print("10 nm / d = %.2f 個、10/0.235 = %.2f" % (10e-9/d, 10/0.235))
n_Si = 8/a_Si**3
print("ケイ素の原子の数密度 8/a^3 = %.3e /m3、1個の立方体の1辺 = %.4f nm、10 nm に %.1f 個" % (n_Si, n_Si**(-1/3)*1e9, 10e-9*n_Si**(1/3)))
rho_Si = 28.0855/NA*8/(a_Si*100)**3
print("ケイ素の密度（格子定数から）%.4f g/cm3" % rho_Si)
vSi = 28.1/(2.33*6.02e23)*1e-6
print("例題1の方法：28.1/(2.33×6.02e23) = %.3e m3 → a = %.3f nm → 10 nm に %.1f 個" % (vSi, vSi**(1/3)*1e9, 10/(vSi**(1/3)*1e9)))
print("10 nm の立方体に入る原子：%.0f 個（数密度から）、%.0f 個（43^3）" % ((10e-9)**3*n_Si, 43**3))
print("== やってみよう：20 cm の紙を半分に切り続ける")
for n in [1,2,3,4,5,6,7,8,10,11,17,18,20,21,28,29,30]:
    print("  %2d 回：%.3e m" % (n, 0.20/2**n))
print("0.26 nm まで：log2(0.20/0.26e-9) = %.2f 回" % math.log2(0.20/0.26e-9))
print("0.2 μm まで：log2(0.20/0.2e-6) = %.2f 回" % math.log2(0.20/0.2e-6))
print("1 mm まで：log2(0.20/1e-3) = %.2f 回" % math.log2(0.20/1e-3))
print("2^10 = %d、2^20 = %d、2^30 = %d" % (2**10, 2**20, 2**30))
print("2-7：0.1 mm の紙を42回折る：%.3e km" % (0.1e-3*2**42/1e3))
print("== エネルギーのものさし")
print("300 K の kT = %.4f eV" % (1.380649e-23*300/e))
print("光子 hc/λ：700 nm %.2f eV、400 nm %.2f eV（hc=1240 eV nm）" % (1240/700, 1240/400))
print("hc（CODATA）= %.2f eV nm" % (6.62607015e-34*299792458/e*1e9))
print("200 MeV / 0.0259 eV = %.2e" % (200e6/0.0259))
print("X 線 60 keV / 可視 2 eV = %.0f" % (60e3/2))
print("== 長さのものさし")
for A, nm in [(1,'H'), (12,'C'), (27,'Al'), (56,'Fe'), (238,'U')]:
    print("  1.2 A^(1/3) fm：%s %.2f fm" % (nm, 1.2*A**(1/3)))
print("アルミの原子 0.26 nm / 原子核（直径 2×3.6 fm）= %.2e" % (0.26e-9/(2*1.2*27**(1/3)*1e-15)))
print("原子を直径 100 m にすると、原子核の直径は %.1f mm" % (100/(0.26e-9/(2*3.6e-15))*1000))
for x in [2e-2, 7.8e-7, 3.8e-7, 2e-7, 10e-9, 0.26e-9, 7.2e-15]:
    print("  log10(%.2e m) = %.2f" % (x, math.log10(x)))
for E in [0.0259, 1.77, 3.10, 4.1, 13.6, 60e3, 0.662e6, 200e6]:
    print("  log10(%.4g eV) = %.2f" % (E, math.log10(E)))
print("== 本文のそのほか")
print("1 mm に並ぶ原子：1e-3/0.255e-9 = %.2e、1e-3/0.26e-9 = %.2e" % (1e-3/0.2551e-9, 1e-3/0.26e-9))
print("はば 5 nm：5/0.235 = %.1f 個" % (5/0.235))
