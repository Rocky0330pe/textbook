# 物理第4巻 電-0（序章）の数値の確かめ。python3 calc_p4_00.py > calc_p4_00_out.txt
import math
print("== 家庭の電圧（電気事業法施行規則 第38条）")
print("100 V:", 101-6, "〜", 101+6, "V   200 V:", 202-20, "〜", 202+20, "V")
print("100 V の山（実効値×√2）:", round(100*math.sqrt(2), 1), "V")

print("\n== 例題1 ドライヤー 100 V・1200 W")
P, V = 1200, 100
I = P/V
print("I =", I, "A,  R = V/I =", round(V/I, 2), "Ω")
t = 10*60
W = P*t
print("10分の電力量 =", W, "J =", W/3.6e6, "kWh")
print("15 A の延長コードで残り:", 15*V - P, "W")

print("\n== 例題2 400 km の知らせ")
L = 400e3; c = 3.00e8
tt = L/c
print("t = L/c =", tt, "s =", round(tt*1e3, 2), "ms")
e = 1.60e-19; n = 8.49e28; S = 2.0e-6
vd2 = 12/(e*n*S)   # 電-4 例題2 の電子の速さ（12 A・2.0 mm^2 の銅線）
print("電-4 例題2 の v_d =", vd2, "m/s")
T = L/vd2
print("電子が 400 km 進む時間 =", T, "s =", T/(365.25*24*3600), "年")
print("知らせの速さ / 電子の速さ =", c/vd2)
lam = c/50
print("50 Hz の波長 =", lam/1e3, "km,  400 km は波長の", round(L/lam, 3))
print("50 Hz の周期 20 ms と 1.3 ms の比:", round(tt/0.02, 3))
print("ガラスの光ファイバ（n=1.48）なら:", 1.48*L/c*1e3, "ms（波-0 例題3）")

print("\n== 例題3 100 MW を 10 Ω の線で（単相・力率1として）")
P = 100e6; R = 10
for kV in [66, 100, 154, 200, 275, 500]:
    V = kV*1e3
    I = P/V
    loss = R*I**2
    print(f"{kV:4d} kV: I = {I:8.1f} A, 損失 = {loss/1e6:7.3f} MW = {100*loss/P:6.2f} %")
print("100 kV→500 kV で損失は 1/", (500/100)**2)
print("電圧2倍（100→200 kV）：電流 1/2、損失 1/4 ->", 10/4, "MW")
print("100 kV の線の電圧の下がり RI =", R*1000, "V =", 100*R*1000/1e5, "%")

print("\n== 電圧のものさし（log10）")
for name, v in [("乾電池", 1.5), ("USB", 5), ("家 100 V", 100), ("家 200 V", 200), ("配電 6600 V", 6600),
                ("送電 66 kV", 66e3), ("送電 154 kV", 154e3), ("送電 275 kV", 275e3), ("送電 500 kV", 500e3)]:
    print(f"{name:12s} {v:>10g} V  log10 = {math.log10(v):.3f}")
print("500 kV / 100 V =", 500e3/100)
print("500 kV / 1.5 V =", 500e3/1.5)

print("\n== 発電機（電-12 ⑧）")
for f in (50, 60):
    print(f, "Hz, 2極: n_s = 120f/p =", 120*f/2, "min^-1")

