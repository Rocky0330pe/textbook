# 電-8 の数値の検算（組 電W5）。python3 calc_p4_08.py > calc_p4_08_out.txt
import math
pi = math.pi
mu0 = 4 * pi * 1e-7
def p(*a): print(*a)
p("== 例題1・じぶんでとこう1")
p("100巻・1e-4 Wb・0.1 s V:", 100 * 1e-4 / 0.1)
p("200巻・3e-5 Wb・0.02 s V:", 200 * 3e-5 / 0.02)
p("== 例題2：棒")
for v in (2, 4):
    l, B, R = 0.5, 0.1, 1.0
    E = v * B * l; I = E / R; F = I * l * B
    p(f"v={v}: E V={E}, I A={I}, F N={F:.4g}, Fv W={F*v:.4g}, RI^2 W={R*I*I:.4g}")
p("== 例題3：発電機")
for N, S, B, f in ((100, 0.01, 0.5, 50), (100, 0.01, 0.5, 60), (200, 0.01, 0.25, 50)):
    w = 2 * pi * f; Em = N * B * S * w
    p(f"N={N} S={S} B={B} f={f}: 山 V={Em:.4g}, 実効 V={Em/math.sqrt(2):.4g}")
p("== 例題4：翼・車軸")
p("翼 60 m・250 m/s・3.5e-5 T V:", 60 * 250 * 3.5e-5)
p("新幹線の車軸 1.5 m・300 km/h・3.5e-5 T mV:", 1.5 * 300 / 3.6 * 3.5e-5 * 1e3)
p("== 例題5：ソレノイド")
S = pi * 0.01 ** 2
for N in (1000, 500):
    L = mu0 * N * N * S / 0.1
    p(f"N={N}: L mH={L*1e3:.4g}")
p("鉄心 μr=1000: L H=", 1000 * mu0 * 1000 ** 2 * S / 0.1)
p("⑥ 同軸ケーブル L' = μ0/(2π) ln(1.6/0.45) μH/m:", mu0 / (2 * pi) * math.log(1.6 / 0.45) * 1e6)
p("== 例題6：リレーを切る")
p("0.2 H・30 mA・0.1 ms V:", 0.2 * 0.03 / 1e-4)
p("0.2 H・30 mA・1 μs V:", 0.2 * 0.03 / 1e-6)
p("== 例題7：相互誘導")
p("M 0.01・100 A/s V:", 0.01 * 100)
M = mu0 * 1000 * 100 * S / 0.1
p("M（1000巻と100巻・0.1 m・半径1 cm）H:", M, " 50 A/s の V:", M * 50)
p("== 例題8：エネルギー")
p("リレー 0.2 H・30 mA J:", 0.5 * 0.2 * 0.03 ** 2)
L5 = mu0 * 1000 ** 2 * S / 0.1
B = mu0 * 1000 / 0.1 * 2
p("ソレノイド 2 A：½LI^2 J:", 0.5 * L5 * 4, " B T:", B, " u J/m3:", B * B / 2 / mu0, " u×体積 J:", B * B / 2 / mu0 * S * 0.1)
p("== 例題9：電磁石")
for B in (1.0, 0.5):
    p(f"B={B}: F N（10 cm2・1面）=", B * B * 1e-3 / 2 / mu0)
p("== 例題10：表皮深さ（25 kHz）")
# 銅は電-4 の表の標準軟銅 1.72e-8 Ω·m（IACS 5.80e7 S/m と同じ量。まとめ役の決定 Z-4）
sig_cu = 1 / 1.72e-8; sig_al = 1 / 2.65e-8; sig_fe = 1e7
def skin(f, s, mur=1): return math.sqrt(2 / (2 * pi * f * mur * mu0 * s))
res = {}
for name, s, mur in (("鉄 σ1e7 μr100", sig_fe, 100), ("アルミ", sig_al, 1), ("銅", sig_cu, 1)):
    d = skin(25e3, s, mur); Rs = 1 / (s * d); res[name] = Rs
    p(f"{name}: δ mm={d*1e3:.4g}, 表面の抵抗 1/(σδ) Ω={Rs:.4g}")
p("鉄÷銅:", res["鉄 σ1e7 μr100"] / res["銅"], " 鉄÷アルミ:", res["鉄 σ1e7 μr100"] / res["アルミ"])
p("銅 50 Hz δ mm:", skin(50, sig_cu) * 1e3, " アルミ 90 kHz δ mm:", skin(90e3, sig_al) * 1e3)
p("鉄 50 kHz δ mm:", skin(50e3, sig_fe, 100) * 1e3)
p("δ の表（グラフ用）")
for f in (50, 1e3, 1e4, 2e4, 2.5e4, 1e5):
    p(f, [round(skin(f, s, m) * 1e3, 4) for s, m in ((sig_cu, 1), (sig_al, 1), (sig_fe, 100))])
p("== 例題11：積層")
p("0.35/3.5 の2乗:", (0.35 / 3.5) ** 2, " 0.35/0.5 の2乗:", (0.35 / 0.5) ** 2)
p("== 例題12：IC カード")
for L in (2e-6, 1e-6):
    C = 1 / ((2 * pi * 13.56e6) ** 2 * L)
    p(f"L={L}: C pF={C*1e12:.4g}")
p("== ⑨ うずの電場：半径 0.05 m・0.4 T/s の円")
p("起電力 V:", pi * 0.05 ** 2 * 0.4, " E V/m:", 0.05 / 2 * 0.4)
p("== ⑪ 渦電流損の式の確かめ（数値積分）")
sig, f, Bm, d = 2e6, 50, 1.5, 0.35e-3
w = 2 * pi * f
n = 2000; tot = 0
for i in range(n):
    x = -d / 2 + (i + 0.5) * d / n
    tot += sig * x * x * (w * Bm) ** 2 / 2 * (d / n)
p("数値積分 W/m3:", tot / d, " 式 π²σf²B²d²/6:", pi ** 2 * sig * f * f * Bm * Bm * d * d / 6)
p("== 章末問題")
p("基本1：50巻・4.0e-3 Wb を 0.20 s で0に V:", 50 * 0.004 / 0.2)
p("基本2：棒 0.30 m・0.20 T・5.0 m/s・0.50 Ω：E, I, F, P", 0.3*0.2*5, 0.3*0.2*5/0.5, 0.3*0.2*5/0.5*0.3*0.2, (0.3*0.2*5)**2/0.5)
p("基本3：200巻・0.020 m2・0.25 T・50 Hz の山 V:", 200*0.25*0.02*2*pi*50)
Lb = mu0*400**2*2e-4/0.2
p("基本4：400巻・0.20 m・2.0 cm2 の L H:", Lb, " 3.0 A の U J:", 0.5*Lb*9)
p("基本5：M 0.050・2.0 A を 0.010 s V:", 0.05*2/0.01)
p("基本6：縦のレール m 0.010・l 0.20・B 0.50・R 0.10 の終わりの速さ m/s:", 0.01*9.8*0.1/(0.5**2*0.2**2))
p("チャレンジ1：(0.25/0.5)^2×(400/50)^2:", (0.25/0.5)**2*(400/50)**2)
d1 = skin(1e6, sig_cu)
p("チャレンジ2：銅 1 MHz δ mm:", d1*1e3, " 半径 1 mm の抵抗の比 r/(2δ):", 1e-3/(2*d1))
F1 = 0.8**2*4e-4/(2*mu0)
p("チャレンジ3：0.80 T・4.0 cm2 の1極 N:", F1, " 2極:", 2*F1, " 50 kg を持つ B T:", math.sqrt(50*9.8*2*mu0/(2*4e-4)))
p("例題11：1.0→0.35 mm の比:", 0.35**2, " 50→60 Hz:", 1.2**2)
# 厚い板の補正 F(ξ)=3/ξ (sinhξ−sinξ)/(coshξ−cosξ)（うすい板の式との比）
sig2, mur = 2e6, 1000
dd = skin(50, sig2, mur)
p("電磁鋼板 σ2e6・μr1000・50 Hz の δ mm:", dd*1e3)
for dmm in (1.0, 0.5, 0.35):
    xi = dmm*1e-3/dd
    F = 3/xi*(math.sinh(xi)-math.sin(xi))/(math.cosh(xi)-math.cos(xi))
    p(f"  d={dmm} mm: d/δ={xi:.3f}, 補正={F:.4f}")
p("== ⑪ の Python の出力")
for d_mm in [1.0, 0.5, 0.35, 0.23]:
    d = d_mm/1000; pp = pi**2*2e6*50**2*1.5**2*d**2/6
    p(d_mm, round(pp), round(pp/7650, 2))
