# -*- coding: utf-8 -*-
"""電-7（磁性体と磁気回路）の数をすべて計算する。python3 calc_p4_07.py > calc_p4_07_out.txt
本文の丸め：mu0=4π×10^-7、g=9.8 m/s^2。例題の比透磁率・巻数は仮の値（本文に「〜とします」と書いた）。"""
import math
pi = math.pi
mu0 = 4 * pi * 1e-7
def p(*a): print(*a)

p("== 例題1 鉄の中 1.5 T の磁化 ==")
p("M≈B/μ0 =", 1.5 / mu0, " μr=5000 のときの H =", 1.5 / (mu0 * 5000), " M=B/μ0-H =", 1.5 / mu0 - 1.5 / (mu0 * 5000))
p("じぶん1 1.8 T：", 1.8 / mu0)
p("== 例題2 n=1000・0.1 A・μr=1000 ==")
p("空気", mu0 * 1000 * 0.1, " 鉄心", mu0 * 1000 * 1000 * 0.1, " H=nI", 1000 * 0.1)
p("じぶん2 n=500・0.2 A・μr=2000：", mu0 * 2000 * 500 * 0.2)

def Rm(l, S, mur=1.0):
    return l / (mur * mu0 * S)
p("== 例題3 鉄心 l=0.2・S=4 cm2・μr=2000・200巻・0.5 A ==")
R3 = Rm(0.2, 4e-4, 2000); F3 = 200 * 0.5; Phi3 = F3 / R3
p("Rm =", R3, " Φ =", Phi3, " B =", Phi3 / 4e-4, " H =", F3 / 0.2)
p("じぶん3 l=0.3・S=5 cm2・μr=1000・100巻・1.0 A：", Rm(0.3, 5e-4, 1000), 100 / Rm(0.3, 5e-4, 1000), 100 / Rm(0.3, 5e-4, 1000) / 5e-4)
p("== 例題4 すき間 1 mm ==")
Rg = Rm(1e-3, 4e-4); Rt = R3 + Rg; Phi4 = F3 / Rt
p("Rg =", Rg, " 合計 =", Rt, " Φ =", Phi4, " B =", Phi4 / 4e-4, " すき間の割合 =", Rg / Rt)
p("  すき間 2 mm：B =", F3 / (R3 + Rm(2e-3, 4e-4)) / 4e-4, " 比", (F3 / (R3 + Rm(2e-3, 4e-4))) / Phi4)
Rg5 = Rm(0.5e-3, 4e-4); p("じぶん4 すき間 0.5 mm：Rg =", Rg5, " Φ =", F3 / (R3 + Rg5), " B =", F3 / (R3 + Rg5) / 4e-4, " 割合", Rg5 / (R3 + Rg5))
p("== 例題5 すき間 1 mm で 0.5 T ==")
Hg = 0.5 / mu0; Hi = 0.5 / (mu0 * 2000)
p("すき間 NI =", Hg * 1e-3, " 鉄 NI =", Hi * 0.2, " 合計 =", Hg * 1e-3 + Hi * 0.2)
p("じぶん5 すき間 2 mm・0.4 T：", 0.4 / mu0 * 2e-3, 0.4 / (mu0 * 2000) * 0.2, 0.4 / mu0 * 2e-3 + 0.4 / (mu0 * 2000) * 0.2)
p("== 例題6 リレー 12 V・400 Ω・2000巻・すき間 0.5 mm ==")
I6 = 12 / 400; p("I =", I6, " NI =", 2000 * I6, " B =", mu0 * 2000 * I6 / 0.5e-3)
p("じぶん6 5 V・125 Ω・1000巻・0.4 mm：I =", 5 / 125, " B =", mu0 * 1000 * 5 / 125 / 0.4e-3)
p("== 例題7 ヒステリシス損 Bmax=1.5・Hc=50 ==")
w = 4 * 1.5 * 50; p("1周", w, "J/m3  50 Hz:", w * 50, "W/m3  ÷7650:", w * 50 / 7650, "W/kg")
w = 4 * 1.2 * 30; p("じぶん7 1.2 T・30 A/m・60 Hz：", w, w * 60, w * 60 / 7650)
p("== 例題8 境界 μr=1000、鉄の中で法線から 80° ==")
t = math.tan(math.radians(80)) / 1000; p("空気側 法線から", math.degrees(math.atan(t)), "°")
t = math.tan(math.radians(60)) / 500; p("じぶん8 μr=500・60°：", math.degrees(math.atan(t)))
p("== 例題9 地磁気 46000 nT の H ==")
p(46e-6 / mu0, " じぶん9 30 μT：", 30e-6 / mu0)
p("== 例題10 水の浮上 χ=-9.0e-6 ==")
G = mu0 * 1000 * 9.8 / 9.0e-6; p("B dB/dz =", G, " 16 T のとき dB/dz =", G / 16)
p("じぶん10 月（g=1.62）：", mu0 * 1000 * 1.62 / 9.0e-6)
p("== 例題11 永久磁石の動作点 l_m=5 mm・すき間 1 mm ==")
def Bop(Br, mrec, lm, g):
    return Br / (1 + mrec * g / lm)
Bn = Bop(1.3, 1.05, 5, 1); Bf = Bop(0.40, 1.1, 5, 1)
p("ネオジム", Bn, " フェライト", Bf, " 比 B^2", (Bn / Bf) ** 2, " Br の比の2乗", (1.3 / 0.4) ** 2)
p("1 cm2 あたりの力 B^2 S/(2μ0)：", Bn**2 * 1e-4 / (2 * mu0), Bf**2 * 1e-4 / (2 * mu0))
p("  H_m（ネオジム）=", -(Bn * 1) / (mu0 * 5), " A/m")
p("じぶん11 l_m=10 mm・1 mm：", Bop(1.3, 1.05, 10, 1))
p("== 例題12 外鉄形 中央 l=0.1・S=4 cm2、外 l=0.3・S=2 cm2、μr=2000、100 A ==")
Rc = Rm(0.1, 4e-4, 2000); Ro = Rm(0.3, 2e-4, 2000); Rt = Rc + Ro / 2; Phi = 100 / Rt
p("Rc =", Rc, " Ro =", Ro, " 合計 =", Rt, " Φ =", Phi, " B中央 =", Phi / 4e-4, " 外 Φ/2 =", Phi / 2, " B外 =", Phi / 2 / 2e-4)
Rc = Rm(0.1, 4e-4, 1000); Ro = Rm(0.3, 2e-4, 1000); Phi = 100 / (Rc + Ro / 2)
p("じぶん12 μr=1000：Φ =", Phi, " B =", Phi / 4e-4)
p("== 表計算：BH ループ（Bs=1.55・Hc=50・a=40、H=-250〜250）の面積 ==")
Bs, Hc, a = 1.55, 50.0, 40.0
Hs = list(range(-250, 251, 50))
up = [Bs * math.tanh((h - Hc) / a) for h in Hs]
dn = [Bs * math.tanh((h + Hc) / a) for h in Hs]
for h, u, d in zip(Hs, up, dn):
    p(h, round(d, 3), round(u, 3), round(d - u, 3))
area = sum((dn[k] - up[k] + dn[k + 1] - up[k + 1]) / 2 * 50 for k in range(len(Hs) - 1))
p("台形の和（50 A/m ごと）=", area)
Hf = [h / 10 for h in range(-2500, 2501)]
af = sum((Bs * math.tanh((h + Hc) / a) - Bs * math.tanh((h - Hc) / a)) * 0.1 for h in Hf)
p("細かく（0.1 A/m ごと）=", af, " 4 Bs Hc =", 4 * Bs * Hc)
p("残留 B（H=0 の下りの枝）", Bs * math.tanh(Hc / a))
p("== 章末 ==")
p("1  μr=800・n=2000・0.05 A：", mu0 * 800 * 2000 * 0.05)
p("2  1.6 T：", 1.6 / mu0)
R = Rm(0.4, 2e-4, 1500); p("3  Rm =", R, " Φ =", 60 / R, " B =", 60 / R / 2e-4)
Rg = Rm(0.5e-3, 2e-4); p("4  Rg =", Rg, " Φ =", 60 / (R + Rg), " B =", 60 / (R + Rg) / 2e-4)
p("5  50 μT：", 50e-6 / mu0)
p("6  200 J/m3・400 Hz：", 200 * 400, 200 * 400 / 7650)
p("7  空気側 30°・μr=2000：鉄の中", math.degrees(math.atan(2000 * math.tan(math.radians(30)))))
B8 = Bop(1.2, 1.05, 4, 2); p("8  Br=1.2・l_m=4・g=2：B =", B8, " 1 cm2 の力", B8**2 * 1e-4 / (2 * mu0))
Rc = Rm(0.1, 4e-4, 2000); Ro = Rm(0.3, 2e-4, 2000); Rg = Rm(0.2e-3, 4e-4)
Rt = Rc + Rg + Ro / 2; p("9  中央に 0.2 mm：Rg =", Rg, " 合計 =", Rt, " Φ =", 100 / Rt, " B =", 100 / Rt / 4e-4)
p("== 相似の表：磁気エネルギー（すき間 1 mm・例題4）==")
Phi4 = F3 / (R3 + Rm(1e-3, 4e-4))
p("全体 1/2 Rm Φ^2 =", 0.5 * (R3 + Rm(1e-3, 4e-4)) * Phi4**2, " すき間の分 =", 0.5 * Rm(1e-3, 4e-4) * Phi4**2)
