def phidip(z, d=0.01, q=1e-9):
    return k * q * (1 / (z - d / 2) - 1 / (z + d / 2))


def Edip(z, d=0.01, q=1e-9):
    return k * q * (1 / (z - d / 2) ** 2 - 1 / (z + d / 2) ** 2)


for z in (0.099, 0.1, 0.101):
    p('双極子の電位 z=%.3f' % z, phidip(z))
