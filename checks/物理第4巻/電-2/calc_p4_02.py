def laplace(top, bottom, left, right, N=5, it=3000):
    T = [[0.0] * N for _ in range(N)]
    for j in range(1, N - 1):
        T[0][j] = top
        T[N - 1][j] = bottom
    for i in range(1, N - 1):
        T[i][0] = left
        T[i][N - 1] = right
    for _ in range(it):
        U = [row[:] for row in T]
        for i in range(1, N - 1):
            for j in range(1, N - 1):
                U[i][j] = (T[i - 1][j] + T[i + 1][j] + T[i][j - 1] + T[i][j + 1]) / 4
        T = U
    return T


