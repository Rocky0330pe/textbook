def relax(N, top=100.0, right=0.0, n=500):
    V = np.zeros((N, N)); V[0, 1:N-1] = top; V[1:N-1, N-1] = right
    for _ in range(n):
        W = V.copy()
        W[1:N-1, 1:N-1] = (V[0:N-2, 1:N-1] + V[2:N, 1:N-1] + V[1:N-1, 0:N-2] + V[1:N-1, 2:N]) / 4
        V = W
    return V


