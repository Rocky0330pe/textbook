# -*- coding: utf-8 -*-
"""電-6（電流がつくる磁場）の数をすべて計算する。python3 calc_p4_06.py > calc_p4_06_out.txt
本文の丸め：mu0=4π×10^-7、e=1.60×10^-19 C、m_e=9.11×10^-31 kg、m_p=1.67×10^-27 kg（2けたの答え）。"""
import math
pi = math.pi
mu0 = 4 * pi * 1e-7
e = 1.60e-19
me = 9.11e-31
mp = 1.67e-27

def line(I, r):      # まっすぐな電流
    return mu0 * I / (2 * pi * r)

def p(*a):
    print(*a)

p("== 定数 ==")
mu0_codata = 1.25663706127e-6
p("4π×10^-7 =", 4 * pi * 1e-7, " CODATA 2022 =", mu0_codata, " 相対の差 =", (mu0_codata - mu0) / mu0)
p("BIPM：2019年の改定のときの相対標準不確かさ 2.3e-10")

p("== 例題1 方位磁針 10 A・5 cm、地磁気の水平 3.0e-5 T ==")
B = line(10, 0.05); p("B =", B, " ふれ =", math.degrees(math.atan(B / 3.0e-5)))
p("じぶん1 5 A・5 cm：", line(5, 0.05), math.degrees(math.atan(line(5, 0.05) / 3.0e-5)))
p("  45°になる距離（10 A）：", mu0 * 10 / (2 * pi * 3.0e-5))
p("== 例題2 円形コイル 10巻・1 A・半径 5 cm ==")
p(mu0 * 10 * 1 / (2 * 0.05))
p("じぶん2 50巻・0.5 A・10 cm：", mu0 * 50 * 0.5 / (2 * 0.10))
p("== 例題3 ソレノイド 1000巻/m・2 A ==")
p(mu0 * 1000 * 2)
p("じぶん3 20 cm・400巻・0.5 A：n=2000：", mu0 * 2000 * 0.5, " 0.010 T に要る電流：", 0.010 / (mu0 * 2000))
p("== 例題4 環状コイル 500巻・1 A・半径 0.1 m ==")
p(mu0 * 500 / (2 * pi * 0.1), " 内 0.09：", mu0 * 500 / (2 * pi * 0.09), " 外 0.11：", mu0 * 500 / (2 * pi * 0.11))
p("じぶん4 1000巻・2 A・半径 5 cm：", mu0 * 1000 * 2 / (2 * pi * 0.05))
p("== 例題5 3 A・0.2 m・0.5 T ==")
p(3 * 0.2 * 0.5, " 30°：", 3 * 0.2 * 0.5 * math.sin(math.radians(30)))
p("じぶん5 2 A・0.1 m・0.4 T：", 2 * 0.1 * 0.4, " 60°：", 2 * 0.1 * 0.4 * math.sin(math.radians(60)))
p("== 例題6 1 A・1 A・1 m ==")
p(mu0 * 1 * 1 / (2 * pi * 1))
p("じぶん6 5 A・3 A・2 cm：", mu0 * 5 * 3 / (2 * pi * 0.02))
p("== 例題7 家のコード 10 A・3 mm ==")
f = mu0 * 10 * 10 / (2 * pi * 0.003); p(f, " 2 m のコードで", 2 * f, " 1000 A：", mu0 * 1000**2 / (2 * pi * 0.003), " 比", (1000 / 10)**2)
p("じぶん7 15 A・4 mm：", mu0 * 15**2 / (2 * pi * 0.004))
p("== 例題8 1 kV の電子・1 mT ==")
v = math.sqrt(2 * e * 1000 / me); r = me * v / (e * 1e-3); p("v =", v, " r =", r, " 周期 =", 2 * pi * me / (e * 1e-3))
v = math.sqrt(2 * e * 100 / me); p("じぶん8 100 V：v =", v, " r =", me * v / (e * 1e-3))
p("== 例題9 陽子・1 T ==")
p(e * 1 / (2 * pi * mp))
p("じぶん9 電子・1 mT：", e * 1e-3 / (2 * pi * me))
p("  陽子の速さ 1e7 m/s のときの半径（1 T）：", mp * 1e7 / (e * 1))
p("== 例題10 ホール素子 n=1e22・1 mA・0.10 T・厚さ 0.20 mm ==")
p(1e-3 * 0.10 / (1e22 * e * 0.20e-3))
p("じぶん10 0.50 mV のときの B：", 0.50e-3 * 1e22 * e * 0.20e-3 / 1e-3)
p("  電子の速さ（はば 1 mm とする）：", 1e-3 / (1e22 * e * 1e-3 * 0.20e-3))
p("== 例題11 コイルのトルク 100巻・2 cm角・10 mA・0.2 T ==")
p(100 * 10e-3 * (0.02**2) * 0.2)
p("じぶん11 50巻・3×4 cm・20 mA・0.1 T：", 50 * 0.02 * 12e-4 * 0.1, " 30°：", 50 * 0.02 * 12e-4 * 0.1 * 0.5)
p("== 例題12 送電線 1000 A・20 m ==")
B1 = line(1000, 20); p(B1, " 地磁気46μT との比", B1 / 46e-6, " 200μT との比", B1 / 200e-6)
# 往復の2本（間 1 m）を、まん中の真下 20 m で、ベクトルで足す
def Bvec(I, x0, y0, x, y):
    dx, dy = x - x0, y - y0; r2 = dx * dx + dy * dy
    k = mu0 * I / (2 * pi * r2)
    return (-k * dy, k * dx)   # z 向きの電流のまわり（右ねじ）
b1 = Bvec(1000, -0.5, 0, 0, -20); b2 = Bvec(-1000, 0.5, 0, 0, -20)
p("往復 1 m：", math.hypot(b1[0] + b2[0], b1[1] + b2[1]), " 近似 μ0 I d/(2π r^2)=", mu0 * 1000 * 1 / (2 * pi * 400))
p("じぶん12 200 A・10 m：", line(200, 10))
b1 = Bvec(200, -0.3, 0, 0, -10); b2 = Bvec(-200, 0.3, 0, 0, -10)
p("  往復 0.6 m：", math.hypot(b1[0] + b2[0], b1[1] + b2[1]), " 近似", mu0 * 200 * 0.6 / (2 * pi * 100))
p("== 例題13 速度選別器 E=1e4・B=0.01 ==")
p(1e4 / 0.01)
p("じぶん13 E=2e4 で 4e6 m/s：B =", 2e4 / 4e6)
p("== 章末 ==")
p("1  20 A・4 cm：", line(20, 0.04), " 8 cm：", line(20, 0.08))
p("2  0.3 m・600巻・1.5 A：", mu0 * 2000 * 1.5)
p("3  20巻・4 cm・0.8 A：", mu0 * 20 * 0.8 / (2 * 0.04))
p("4  0.5 m・4 A・0.3 T：", 0.5 * 4 * 0.3)
p("5  10 A・10 A・5 cm：", mu0 * 100 / (2 * pi * 0.05))
p("6  陽子 2.0e6 m/s・0.5 T：", mp * 2.0e6 / (e * 0.5))
vv = 2.0e4 / 0.05; r1 = mp * vv / (e * 0.05); r2 = 2 * mp * vv / (e * 0.05)
p("7  選別 v =", vv, " 陽子 r =", r1, " 重水素（2倍の質量）r =", r2, " 着く点の差 2(r2-r1) =", 2 * (r2 - r1))
p("8  反対向き 10 A・間 10 cm のまん中：", 2 * line(10, 0.05))
p("9  環状 400巻・2 A：内 8 cm", mu0 * 800 / (2 * pi * 0.08), " 外 12 cm", mu0 * 800 / (2 * pi * 0.12))
p("10 銅 n=8.5e28・10 A・1 T・0.1 mm：", 10 * 1 / (8.5e28 * e * 1e-4))
p("== 有限のソレノイド（Python の囲み） 半径 2 cm・長さ 10 cm・100巻・1 A ==")
a, L, N, I = 0.02, 0.10, 100, 1.0
zs = [-L / 2 + L * (k + 0.5) / N for k in range(N)]
def Baxis(z):
    return sum(mu0 * I * a * a / (2 * (a * a + (z - zk) ** 2) ** 1.5) for zk in zs)
for z in [0, 0.025, 0.05, 0.075, 0.10]:
    c1 = (L / 2 - z) / math.hypot(L / 2 - z, a); c2 = (L / 2 + z) / math.hypot(L / 2 + z, a)
    p(z, Baxis(z) * 1000, " 式", mu0 * N / L * I * (c1 + c2) / 2 * 1000)
p("無限に長いとき μ0 n I =", mu0 * N / L * I * 1000, "mT")
p("== 2倍の図 ==")
for r in [0.05, 0.10, 0.15, 0.20]:
    p("r", r, "B(10 A)", line(10, r) * 1e6, "μT")
p("== 図：ふれの角と電流（5 cm・地磁気 3.0e-5）==")
for I in [0, 2, 5, 10, 20, 50]:
    p(I, round(math.degrees(math.atan(line(I, 0.05) / 3.0e-5)), 1))
p("== 地磁気（IGRF-11 東京 2014：北大の授業資料）H=30208.5 nT、F=46387.1 nT、I=49.366°")
p("H/F =", 30208.5 / 46387.1, " cos I =", math.cos(math.radians(49.366)))
p("鉛直 Z =", math.sqrt(46387.1**2 - 30208.5**2))
p("== MRI 3 T と地磁気 ==", 3 / 46e-6, 1.5 / 46e-6)
