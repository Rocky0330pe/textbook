import numpy as np                 # 数の表の道具 numpy を np という名前で使う
x = np.arange(0, 60, 10)           # 東へ 0, 10, …, 50（m）。60 は入らない
y = np.arange(40, -10, -10)        # 北へ 40, 30, …, 0（m）。北を上にするため大きい順
X, Y = np.meshgrid(x, y)           # 地図のマスごとの x と y の表
H = 100 - 0.01*X**2 - 0.02*Y**2    # マスごとの高さ（表計算の B2 の式と同じ）
print(H)
print(H[2, 3])                     # 上から2行め・左から3列め（0から数える）
