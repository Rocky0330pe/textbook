def math_vols(ref):
    """「4-11・S13」→ 使う数学の巻（重なりなし・小さい順）"""
    vols = set()
    for t in ref.split("・"):
        t = t.strip()
        if not t: continue
        if t.startswith("S"): t = S_TO_MATH[t]
        vols.add(int(t.split("-")[0]))
    return sorted(vols)

FRONT_PAGES = 7   # p1 扉、p2-3 もくじ、p4-5 保存則と相似の地図、p6-7 この本の使い方
def chap_pages(kind, smax):
    if kind == "J": return 4
    if kind == "R": return 8
    return 18 if smax >= 5 else 16

