def layout(v):
    out, back, page = _layout_plan(v)
    act = ACTUAL.get(str(v["no"]))
    if not act:
        return out, back, page
    page = FRONT_PAGES + 1
    out2 = []
    for o in out:
        if o[0] == "part":
            out2.append(("part", o[1], o[2], o[3], page)); page += 2
        else:
            c = o[1]
            out2.append(("chap", c, page))
            page += act["chap"].get(c[0], chap_pages(c[5], c[3][1]))
    back2 = []
    for i, (name, pg) in enumerate(back):
        back2.append((name, page))
        nxt = back[i + 1][1] if i + 1 < len(back) else None
        page += act["back"].get(name, (nxt - pg) if nxt else 2)
    total = act.get("total") or page
    return out2, back2, total

def _layout_plan(v):
    page = FRONT_PAGES + 1
    out = []; nmain = 0
    for plabel, pname, face, chs in v["parts"]:
        if pname is not None:
            out.append(("part", plabel, pname, face, page)); page += 2
        for c in chs:
            assert page % 2 == 0, (c[0], page)
            out.append(("chap", c, page))
            page += chap_pages(c[5], c[3][1])
            if c[5] in ("C", "R"): nmain += 1
    # 巻末（見つもり）：こたえ（1章0.5ページ）、記号カード3（分野で記号がぶつかる表をふくむ）、
    # 物性値・定数・単位（4の倍数に調える）、なぜ？の道すじ2、チェック表、つぎの巻へ2、さくいん2、奥付1
    ans = math.ceil(nmain * 0.5)
    chk = max(1, math.ceil(nmain * 3 / 30))
    tname, tbase = v.get("tables", ("物性値・定数・単位", 4))
    sizes = [("こたえ", ans), ("記号カード", 3), (tname, tbase), ("なぜ？の道すじ", 2),
             ("チェック表", chk), ("つぎの巻へ", 2), ("さくいん", 2)]
    total = page + sum(n for _, n in sizes)
    sizes[2] = (tname, tbase + (-total) % 4)
    back = []
    for name, n in sizes:
        back.append((name, page)); page += n
    assert page % 4 == 0
    return out, back, page   # page＝奥付のノンブル

